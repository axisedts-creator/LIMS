// T0D-ELABMENU-3 notes-table generator (tester-owned). Not an assertion about the code: every run writes
// .orchestra/notes/T0D-ELABMENU-3-table.md (sidebar entry -> route -> heading key/text -> state), the table done_when (1) asks for FIRST.
import { describe, expect, it } from 'vitest';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, matches, rows } from './elabmenu3.helpers';

const cell = (s: string) => s.replace(/\|/g, '\\|');
const headingCell = (r: (typeof rows)[number]) =>
  r.page === null ? '(no page.tsx: catch-all)' : r.headings.length === 0 ? '(none found)' : r.headings.map((h) => (h.kind === 'dynamic' ? `<dynamic: ${h.raw}>` : h.kind === 'key' ? `${h.raw} = "${h.text}"` : `"${h.text}"`)).join(' ; ');

describe('notes table', () => {
  it('has one row per generated manifest entry', () => {
    expect(rows.length).toBeGreaterThan(100);
    expect(new Set(rows.map((r) => r.id)).size).toBe(rows.length);
  });

  it('writes .orchestra/notes/T0D-ELABMENU-3-table.md (regenerated on every run, so the writer sees the current state)', () => {
    const lines = [
      '# T0D-ELABMENU-3 sidebar entry table (generated by elabmenu3.table.test.ts on every run)',
      `${rows.length} entries. State: OK = a heading equals the menu label; DIFF = heading text differs; NONE = no static heading found; DYN = heading only dynamic; PIN = page pinned by rs-c2.static (message value only).`,
      '',
      '| entry id | group / section | menu label (key) | route | page file | page heading (key = text) | empty state | state |',
      '|---|---|---|---|---|---|---|---|',
      ...rows.map((r) => {
        const state = matches(r) ? 'OK' : r.headings.length === 0 ? 'NONE' : r.headings.every((h) => h.kind === 'dynamic') ? 'DYN' : 'DIFF';
        return `| ${r.id} | ${cell(r.group + (r.section ? ' / ' + r.section : ''))} | ${cell(`${r.label} (${r.labelKey})`)} | ${r.path} | ${r.page ?? ''} | ${cell(headingCell(r))} | (writer fills: menu-label wording) | ${state}${r.pinned ? ' PIN' : ''} |`;
      }),
    ];
    const out = join(ROOT, '.orchestra', 'notes');
    mkdirSync(out, { recursive: true });
    writeFileSync(join(out, 'T0D-ELABMENU-3-table.md'), lines.join('\n') + '\n');
  });
});
