// Build step (04-UI-UX §3): scans <features>/*/nav.manifest.ts → core/nav/generated.ts (gitignored).
// Fails (exit 1) on: duplicate id or chord (naming both modules, AC-0D-7.5), routeId not in routes.yaml,
// non-staff_web or parameterised route, permission ≠ the route's permission, module ≠ directory.
// Run: node src/core/nav/build-nav.ts   (features dir overridable with LIMS_WEB_FEATURES_DIR)
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { parse } from 'yaml';
import { NAV_GROUPS, type NavManifest, type ResolvedNavEntry, type StaffRoute } from './types.ts';

const HERE = import.meta.dirname;
const SRC = join(HERE, '..', '..');
const ROUTES_FILE = join(SRC, '..', '..', '..', 'contracts', 'routes.yaml');
const OUT = join(HERE, 'generated.ts');

interface RouteRow { id: string; origin: string; path: string; permission?: string }

export async function buildNav(featuresDir: string, routesYaml: string) {
  const routes = (parse(routesYaml) as { routes: RouteRow[] }).routes;
  const staff: StaffRoute[] = routes
    .filter((r) => r.origin === 'staff_web' && r.permission)
    .map((r) => ({ id: r.id, path: r.path, permission: r.permission! }));
  const byId = new Map(routes.map((r) => [r.id, r]));
  const errors: string[] = [];
  const entries: ResolvedNavEntry[] = [];
  const seenId = new Map<string, string>();
  const seenChord = new Map<string, string>();

  const dirs = existsSync(featuresDir) ? readdirSync(featuresDir, { withFileTypes: true }).filter((d) => d.isDirectory()) : [];
  for (const d of dirs.map((x) => x.name).sort()) {
    const file = join(featuresDir, d, 'nav.manifest.ts');
    if (!existsSync(file)) continue;
    const { navManifest } = (await import(pathToFileURL(file).href)) as { navManifest: NavManifest };
    if (navManifest?.module !== d) { errors.push(`${file}: module "${navManifest?.module}" must equal directory "${d}"`); continue; }
    for (const e of navManifest.entries) {
      const where = `${d} (${e.id})`;
      if (seenId.has(e.id)) errors.push(`duplicate nav id "${e.id}": ${seenId.get(e.id)} and ${where}`);
      seenId.set(e.id, where);
      if (e.chord) {
        if (seenChord.has(e.chord)) errors.push(`duplicate shortcut chord "${e.chord}": ${seenChord.get(e.chord)} and ${where}`);
        seenChord.set(e.chord, where);
      }
      if (!(NAV_GROUPS as readonly string[]).includes(e.group)) errors.push(`${where}: unknown group "${e.group}"`);
      const r = byId.get(e.routeId);
      if (!r) { errors.push(`${where}: routeId "${e.routeId}" not found in contracts/routes.yaml`); continue; }
      if (r.origin !== 'staff_web') errors.push(`${where}: route "${r.id}" is not a staff_web route`);
      if (r.path.includes('{')) errors.push(`${where}: route "${r.id}" has path parameters; detail pages are not nav entries`);
      if (r.permission !== e.permission)
        errors.push(`${where}: permission "${e.permission}" differs from route "${r.id}" permission "${r.permission}"`);
      entries.push({ ...e, module: d, path: r.path });
    }
  }
  const groupIdx = (g: string) => (NAV_GROUPS as readonly string[]).indexOf(g);
  entries.sort((a, b) => groupIdx(a.group) - groupIdx(b.group) || a.order - b.order || a.id.localeCompare(b.id));
  return { errors, entries, staff };
}

if (import.meta.main) {
  const featuresDir = process.env.LIMS_WEB_FEATURES_DIR ?? join(SRC, 'features');
  const { errors, entries, staff } = await buildNav(featuresDir, readFileSync(ROUTES_FILE, 'utf8'));
  if (errors.length) {
    for (const e of errors) console.error(`build-nav: ${e}`);
    process.exit(1);
  }
  writeFileSync(OUT, [
    '// GENERATED by core/nav/build-nav.ts — do not edit (gitignored).',
    "import type { ResolvedNavEntry, StaffRoute } from './types';",
    `export const navEntries: readonly ResolvedNavEntry[] = ${JSON.stringify(entries, null, 2)};`,
    `export const staffRoutes: readonly StaffRoute[] = ${JSON.stringify(staff, null, 2)};`,
    '',
  ].join('\n'));
  console.log(`build-nav: ${entries.length} nav entries, ${staff.length} staff routes → ${OUT}`);
}
