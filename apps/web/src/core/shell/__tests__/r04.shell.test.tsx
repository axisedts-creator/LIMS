// CONTRACT chosen by the tester where the spec gives no API (writer: follow it, or dispute via .orchestra/notes):
//   <AppShell session pathname centres?>  centres = { options: {id,name}[]; activeId: string | null } (optional; omitted -> no switcher).
//   Rail = the PageShell <nav aria-label="Main"> (kit `.lims-shell-nav`). Carries data-collapsed="false"|"true". A <button aria-expanded> inside it,
//     named /collapse/i while expanded and /expand/i while collapsed, toggles it. Collapsed keeps every link's accessible name (the visible text may be hidden).
//   Groups: one role="group" per non-empty rail group, accessible name = group label, containing the item links. Rail groups in order:
//     Front desk · Lab · Reports · Accounts · Catalog · Instruments · People & access · Settings   (labels come from t('core.nav.group.<id>') = RAIL_GROUPS[i].labelKey)
//     Every existing NavGroup value is mapped onto one of them by railGroupFor() (see core/nav/rail-groups.ts, tested in nav/__tests__/r04.groups.test.ts).
//   Active item: <a aria-current="page"> (exact pathname match, as today). Entries come only from navEntries (generated by build-nav.ts) filtered by permission.
//   Collapsed tooltip: focusing or hovering a link while collapsed shows an element role="tooltip" with the label, and the link has aria-describedby -> it. Esc hides it.
//   Top bar = banner landmark: searchbox (see r04.search/keys), centre switcher (CentreSwitcher: a control named /centre/i + options, active name visible), actor name.
//   CentreSwitcher({ centres, activeId, onSelect(id) }) in core/shell/CentreSwitcher.tsx. Persisting the active centre has NO contract today -> writer raises a CR (not tested).
import { describe, expect, it, vi } from 'vitest';
import { render, screen, within } from '@testing-library/react';
import { ALL_PERMS, CENTRES, EXPECTED_RAIL, ENTRIES, seriousViolations, session, user } from './r04.harness';
import { AppShell } from '../AppShell';
import * as CentreMod from '../CentreSwitcher';

vi.mock('next/navigation', async () => (await import('./r04.harness')).navigationMock);
vi.mock('next/link', async () => (await import('./r04.harness')).linkMock);
vi.mock('server-only', () => ({}));
vi.mock('@/core/session/server', async () => (await import('./r04.harness')).sessionMock);
vi.mock('@/core/session/actions', async () => (await import('./r04.harness')).actionsMock);
vi.mock('@/core/nav/generated', async () => (await import('./r04.harness')).generatedMock);

const mount = (perms: string[] = ALL_PERMS, pathname = '/lab/worklist', centres?: typeof CENTRES) =>
  render(
    <AppShell session={session(perms) as any} pathname={pathname} {...(centres ? { centres } : {})}>
      <p>page body</p>
    </AppShell>,
  );
const rail = () => screen.getByRole('navigation', { name: 'Main' });
const names = (el: HTMLElement) => within(el).queryAllByRole('link').map((a) => a.textContent?.trim() ?? '');

const openAll = async () => {
  const u = user();
  const out: Record<string, string[]> = {};
  for (const g of within(rail()).getAllByRole('group')) {
    const label = g.getAttribute('aria-label')!;
    const h = within(g).getByRole('button', { name: new RegExp(`^${label}`) });
    if (h.getAttribute('aria-expanded') !== 'true') await u.click(h);
    out[label] = within(g).getAllByRole('link').map((a) => a.textContent?.trim() ?? '');
  }
  return out;
};

describe('sidebar: generated, grouped, permission-filtered (AC 10-DESIGN-SYSTEM §3, 13-M-SERIES s3)', () => {
  it('shows the groups of the staff shell in spec order (no platform group), each with its entries in manifest order', async () => {
    mount();
    const groups = within(rail()).getAllByRole('group');
    expect(groups.map((g) => g.getAttribute('aria-label'))).toEqual(EXPECTED_RAIL.map(([l]) => l));
    expect(await openAll()).toEqual(Object.fromEntries(EXPECTED_RAIL));
    expect(screen.queryByText('Tenants')).toBeNull();
  });

  it('every link points at the manifest path (nothing hard-coded in the shell)', async () => {
    mount();
    await openAll();
    // 13-M-SERIES s3: one group open at a time, so closed groups are hidden; read hrefs from the DOM, not the a11y tree.
    const hrefs = new Map([...rail().querySelectorAll('li[data-entry-id] > a')].map((a) => [a.textContent?.trim(), a.getAttribute('href')]));
    for (const x of ENTRIES.filter((y) => y.group !== 'platform')) expect(hrefs.get(x.label), x.label).toBe(x.path);
  });

  it('a role without a permission sees no entry and no empty group heading', () => {
    mount(['p.lab.worklist']);
    expect(names(rail())).toEqual(['Worklist']);
    expect(within(rail()).getAllByRole('group')).toHaveLength(1);
    for (const hidden of ['Results', 'Register', 'Users', 'Tenants', 'Daily cash', 'Front desk', 'Billing', 'Admin'])
      expect(screen.queryByText(hidden), hidden).toBeNull();
  });

  it('a role with no permissions sees an empty rail (no groups, no links), still a labelled landmark', () => {
    mount([]);
    expect(within(rail()).queryAllByRole('link')).toHaveLength(0);
    expect(within(rail()).queryAllByRole('group')).toHaveLength(0);
    expect(document.body.textContent).not.toContain('Worklist');
  });

  it('permission match is exact (a prefix or a similar code does not unlock an entry)', () => {
    mount(['p.lab.work', 'p.lab.worklist.extra', 'P.LAB.WORKLIST']);
    expect(names(rail())).toEqual([]);
  });

  it('active item = aria-current="page" on exactly the matching link', () => {
    mount(ALL_PERMS, '/lab/results');
    const current = within(rail()).getAllByRole('link').filter((a) => a.getAttribute('aria-current') === 'page');
    expect(current.map((a) => a.textContent?.trim())).toEqual(['Results']);
  });

  it('no active item when the path matches no entry', () => {
    mount(ALL_PERMS, '/nowhere');
    expect(within(rail()).getAllByRole('link').some((a) => a.hasAttribute('aria-current'))).toBe(false);
  });

  it('the page body renders inside <main>', () => {
    mount();
    expect(within(screen.getByRole('main')).getByText('page body')).toBeTruthy();
  });
});

describe('keyboard-only navigation', () => {
  it('Tab reaches the skip link, the search and the Find a screen field, with no positive tabindex (entry order: m2.sidebar.test.tsx)', async () => {
    mount(ALL_PERMS, '/lab/worklist', CENTRES);
    expect(document.querySelectorAll('[tabindex]:not([tabindex="0"]):not([tabindex="-1"])')).toHaveLength(0);
    const u = user();
    const seen: string[] = [];
    for (let i = 0; i < 80; i++) {
      await u.tab();
      const el = document.activeElement as HTMLElement;
      if (!el || el === document.body) break;
      seen.push(el.getAttribute('aria-label') ?? el.textContent?.trim() ?? el.tagName);
    }
    expect(seen.some((s) => /skip to main/i.test(s))).toBe(true);
    expect(seen.some((s) => /search patients/i.test(s))).toBe(true);
    expect(seen).toContain('Find a screen');
    expect(seen).toContain('Worklist'); // the open group (active entry)
  });

  it('a link outside the permission set is not in the Tab sequence', async () => {
    mount(['p.lab.worklist']);
    const u = user();
    const seen: string[] = [];
    for (let i = 0; i < 30; i++) { await u.tab(); seen.push((document.activeElement as HTMLElement).textContent?.trim() ?? ''); }
    expect(seen).toContain('Worklist');
    expect(seen).not.toContain('Results');
  });
});

describe('top bar', () => {
  it('banner landmark holds the search, the actor name and (given centres) the active centre', () => {
    mount(ALL_PERMS, '/lab/worklist', CENTRES);
    const bar = screen.getByRole('banner');
    expect(within(bar).getByRole('searchbox', { name: /search/i })).toBeTruthy();
    expect(within(bar).getByText('Synthetic Technologist')).toBeTruthy();
    expect(within(bar).getByText('Synthetic Centre A')).toBeTruthy(); // active centre always visible
  });

  it('search affordance advertises Ctrl+K and the searchable fields', () => {
    mount();
    expect(within(screen.getByRole('banner')).getByText('Ctrl+K')).toBeTruthy();
    const box = screen.getByRole('searchbox', { name: /search patients/i }); // Find a screen is a second searchbox (13:68, 13:72)
    const hint = `${box.getAttribute('placeholder') ?? ''} ${box.getAttribute('aria-label') ?? ''} ${box.getAttribute('aria-description') ?? ''} ${box.getAttribute('title') ?? ''}`; // LD-344: the short placeholder, the field list in title
    for (const f of [/name/i, /lab code|registration/i, /mobile/i, /patient id|patient code/i, /barcode/i]) expect(hint).toMatch(f);
  });

  it('without centres the shell still renders (no switcher, no crash)', () => {
    mount();
    expect(screen.queryByRole('combobox', { name: /centre/i })).toBeNull();
    expect(screen.getByRole('banner')).toBeTruthy();
  });
});

describe('CentreSwitcher', () => {
  const Switcher: any = (CentreMod as any).CentreSwitcher;
  const pick = async (name: string) => {
    const u = user();
    const ctl = screen.queryByRole('combobox', { name: /centre/i }) ?? screen.getByRole('button', { name: /centre/i });
    if (ctl.tagName === 'SELECT') await u.selectOptions(ctl, name);
    else { await u.click(ctl); await u.click(await screen.findByRole('option', { name })); }
  };

  it('is exported and shows the active centre name', () => {
    expect(Switcher).toBeTypeOf('function');
    render(<Switcher centres={CENTRES.options} activeId={CENTRES.activeId} onSelect={() => {}} />);
    expect(screen.getByText('Synthetic Centre A')).toBeTruthy();
  });

  it('choosing another centre calls onSelect with its id, once', async () => {
    const onSelect = vi.fn();
    render(<Switcher centres={CENTRES.options} activeId={CENTRES.activeId} onSelect={onSelect} />);
    await pick('Synthetic Centre B');
    expect(onSelect).toHaveBeenCalledTimes(1);
    expect(onSelect).toHaveBeenCalledWith(CENTRES.options[1]!.id);
  });

  it('a single centre still shows its name; an unknown activeId or empty list does not crash or show another centre', () => {
    const { unmount } = render(<Switcher centres={[CENTRES.options[0]]} activeId={CENTRES.activeId} onSelect={() => {}} />);
    expect(screen.getByText('Synthetic Centre A')).toBeTruthy();
    unmount();
    render(<Switcher centres={[]} activeId={null} onSelect={() => {}} />);
    expect(screen.queryByText('Synthetic Centre B')).toBeNull();
  });

  it('centre names render as text (XSS) and Devanagari survives', () => {
    const evil = [{ id: 'a', name: '<img src=x onerror=alert(1)>' }, { id: 'b', name: 'सुनिता केन्द्र' }];
    const { container } = render(<Switcher centres={evil} activeId="b" onSelect={() => {}} />);
    expect(container.querySelector('img')).toBeNull();
    expect(screen.getByText('सुनिता केन्द्र')).toBeTruthy();
  });
});

