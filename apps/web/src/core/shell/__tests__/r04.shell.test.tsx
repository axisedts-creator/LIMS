describe('CentreSwitcher', () => {
  const Switcher: any = (CentreMod as any).CentreSwitcher;
  const pick = async (name: string) => {
    const u = user();
    const ctl = screen.queryByRole('combobox', { name: /centre/i }) ?? screen.getByRole('button', { name: /centre/i });
    if (ctl.tagName === 'SELECT') await u.selectOptions(ctl, name);
    else { await u.click(ctl); await u.click(await screen.findByRole('option', { name })); }
  };

  it('is exported and shows the active centre name', () => {
    expect(Switcher).toBeTypeOf('function');
    render(<Switcher centres={CENTRES.options} activeId={CENTRES.activeId} onSelect={() => {}} />);
    expect(screen.getByText('Synthetic Centre A')).toBeTruthy();
  });

  it('choosing another centre calls onSelect with its id, once', async () => {
    const onSelect = vi.fn();
    render(<Switcher centres={CENTRES.options} activeId={CENTRES.activeId} onSelect={onSelect} />);
    await pick('Synthetic Centre B');
    expect(onSelect).toHaveBeenCalledTimes(1);
    expect(onSelect).toHaveBeenCalledWith(CENTRES.options[1]!.id);
  });

  it('a single centre still shows its name; an unknown activeId or empty list does not crash or show another centre', () => {
    const { unmount } = render(<Switcher centres={[CENTRES.options[0]]} activeId={CENTRES.activeId} onSelect={() => {}} />);
    expect(screen.getByText('Synthetic Centre A')).toBeTruthy();
    unmount();
    render(<Switcher centres={[]} activeId={null} onSelect={() => {}} />);
    expect(screen.queryByText('Synthetic Centre B')).toBeNull();
  });

  it('centre names render as text (XSS) and Devanagari survives', () => {
    const evil = [{ id: 'a', name: '<img src=x onerror=alert(1)>' }, { id: 'b', name: 'सुनिता केन्द्र' }];
    const { container } = render(<Switcher centres={evil} activeId="b" onSelect={() => {}} />);
    expect(container.querySelector('img')).toBeNull();
    expect(screen.getByText('सुनिता केन्द्र')).toBeTruthy();
  });
});

