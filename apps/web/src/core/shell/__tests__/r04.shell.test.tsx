// CONTRACT chosen by the tester where the spec gives no API (writer: follow it, or dispute via .orchestra/notes):
//   <AppShell session pathname centres?>  centres = { options: {id,name}[]; activeId: string | null } (optional; omitted -> no switcher).
//   Rail = the PageShell <nav aria-label="Main"> (kit `.lims-shell-nav`). Carries data-collapsed="false"|"true". A <button aria-expanded> inside it,
//     named /collapse/i while expanded and /expand/i while collapsed, toggles it. Collapsed keeps every link's accessible name (the visible text may be hidden).
//   Groups: one role="group" per non-empty rail group, accessible name = group label, containing the item links. Rail groups in order:
//     Front desk · Lab · Reports · Accounts · Catalog · Instruments · People & access · Settings   (labels come from t('core.nav.group.<id>') = RAIL_GROUPS[i].labelKey)
//     Every existing NavGroup value is mapped onto one of them by railGroupFor() (see core/nav/rail-groups.ts, tested in nav/__tests__/r04.groups.test.ts).
//   Active item: <a aria-current="page"> (exact pathname match, as today). Entries come only from navEntries (generated by build-nav.ts) filtered by permission.
//   Collapsed tooltip: focusing or hovering a link while collapsed shows an element role="tooltip" with the label, and the link has aria-describedby -> it. Esc hides it.
//   Top bar = banner landmark: searchbox (see r04.search/keys), centre switcher (CentreSwitcher: a control named /centre/i + options, active name visible), actor name.
//   CentreSwitcher({ centres, activeId, onSelect(id) }) in core/shell/CentreSwitcher.tsx. Persisting the active centre has NO contract today -> writer raises a CR (not tested).
