// Isolation-probe generator (02-TRD §4.5 steps 1-9; AC-0B-3.6 / gate 10; 05-SCHEMA §10). No DB connection, no dependencies.
// Usage: node db/tools/gen-isolation-probes.ts [--root <dir>] [--out <dir>] [--check]
//   reads  <root>/db/meta/tables.yaml (+ optional db/meta/definer-inventory.yaml)
//   writes <out> (default <root>/db/tests/isolation): one <schema>.<table>.test.sql per tenant table (class != G, not rls_exempt)
//          and _registry.sql (psql include: temp tables `registry`, `definer_inventory`). Output is deterministic.
//   --check writes nothing; exit 1 naming every missing/stale/orphan probe file. Invalid identifier / unknown class -> exit 1, nothing written.
// Probe semantics are resolved at run time from the catalog (columns, grants, composite FKs), so a probe never hard-codes table shape.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { readYaml, rootDir, type TableMeta } from "./sql-lib.ts";

const TOOL = "gen-isolation-probes";
const IDENT = /^[a-z_][a-z0-9_]*\.[a-z_][a-z0-9_]*$/;
const CLASSES = new Set(["M", "C", "B", "A", "G"]); // CV §5.2 table classes
const ACTORS = ["partner", "portal", "patient"] as const;
const GENERATED = /^[a-z_][a-z0-9_]*\.[a-z_][a-z0-9_]*\.test\.sql$/; // hand-written suites in the same dir (T0B-08_*.test.sql) never match

const root = rootDir();
const argOut = process.argv.indexOf("--out");
const out = argOut > 0 && process.argv[argOut + 1] ? resolve(process.argv[argOut + 1]) : join(root, "db/tests/isolation");
const check = process.argv.includes("--check");

function die(errs: string[]): never {
  for (const e of errs) console.error(`${TOOL}: ${e}`);
  process.exit(1);
}

const tablesPath = join(root, "db/meta/tables.yaml");
if (!existsSync(tablesPath)) die([`db/meta/tables.yaml not found under ${root}`]);
let tables: Record<string, TableMeta & Record<string, unknown>>;
let definers: Record<string, any>;
try {
  tables = readYaml(tablesPath).tables ?? {};
  definers = readYaml(join(root, "db/meta/definer-inventory.yaml")).definers ?? {};
} catch (e) {
  die([`cannot parse db/meta YAML (JSON subset): ${(e as Error).message}`]);
}

// ---------------------------------------------------------------- validation (before anything is written)
const errs: string[] = [];
for (const [t, d] of Object.entries(tables)) {
  if (!IDENT.test(t)) { errs.push(`invalid table identifier ${JSON.stringify(t)} in tables.yaml (expected schema.table, [a-z0-9_])`); continue; }
  if (!CLASSES.has(String(d.class))) errs.push(`${t}: unknown class ${JSON.stringify(d.class)} (expected M|C|B|A|G)`);
  for (const a of d.shared_with ?? []) if (!(ACTORS as readonly string[]).includes(a)) errs.push(`${t}: shared_with value ${JSON.stringify(a)} not in partner|portal|patient`);
  for (const c of Object.keys(d.columns ?? {})) if (!/^[a-z_][a-z0-9_]*$/.test(c)) errs.push(`${t}: invalid column identifier ${JSON.stringify(c)}`);
}
for (const fn of Object.keys(definers)) if (!IDENT.test(fn)) errs.push(`invalid function identifier ${JSON.stringify(fn)} in definer-inventory.yaml`);
if (errs.length) die(errs);

// ---------------------------------------------------------------- rendering
const lit = (s: unknown) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (xs: unknown[] | undefined) => (xs && xs.length ? `ARRAY[${xs.map(lit).join(", ")}]::text[]` : "ARRAY[]::text[]");
const names = Object.keys(tables).sort();

function registrySql(): string {
  const r = names.map((t) => {
    const d = tables[t];
    return `  (${lit(t)}, ${lit(d.class)}, ${!!d.centre_scoped}, ${!!d.audited}, ${arr(d.shared_with)}, ${!!d.rls_exempt})`;
  });
  const i = Object.keys(definers).sort().map((fn) => {
    const d = definers[fn] ?? {};
    return `  (${lit(fn)}, ${lit(d.owner ?? "")}, ${arr(d.execute)}, ${arr(d.touches)}, ${arr(d.policies)})`;
  });
  return [
    "-- GENERATED by db/tools/gen-isolation-probes.ts from db/meta/tables.yaml + db/meta/definer-inventory.yaml. Do not edit.",
    "-- psql include for registry-driven suites (\\i db/tests/isolation/_registry.sql), run inside the suite's transaction.",
    "CREATE TEMP TABLE registry (tbl text PRIMARY KEY, class text NOT NULL, centre_scoped boolean NOT NULL, audited boolean NOT NULL,",
    "  shared_with text[] NOT NULL, rls_exempt boolean NOT NULL);",
    "CREATE TEMP TABLE definer_inventory (fn text NOT NULL, owner text NOT NULL, execute_roles text[] NOT NULL, touches text[] NOT NULL, policies text[] NOT NULL);",
    r.length ? `INSERT INTO registry (tbl, class, centre_scoped, audited, shared_with, rls_exempt) VALUES\n${r.join(",\n")};` : "-- (no tables registered)",
    i.length ? `INSERT INTO definer_inventory (fn, owner, execute_roles, touches, policies) VALUES\n${i.join(",\n")};` : "-- (no DEFINERs inventoried)",
    "",
  ].join("\n");
}

