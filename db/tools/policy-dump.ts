// Regenerates db/policies/<schema>.sql from pg_policies of a migrated DB (02-TRD §4.1, §4.3 item 9; CV §5.12; AC-0B-2.3).
// Usage: DATABASE_URL=postgres://… node db/tools/policy-dump.ts [--out <dir>]   (default out: db/policies)
// Needs `psql` on PATH. Without a connection it exits 2: it never succeeds silently. CI diffs the output against the committed files.
import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { rootDir } from "./sql-lib.ts";

const url = process.env.DATABASE_URL;
if (!url) { console.error("policy-dump: DATABASE_URL is not set; a migrated database is required"); process.exit(2); }
const i = process.argv.indexOf("--out");
const out = i > 0 ? resolve(process.argv[i + 1]) : join(rootDir(), "db/policies");

const q = `SELECT coalesce(json_agg(p ORDER BY schemaname, tablename, policyname), '[]') FROM (
  SELECT schemaname, tablename, policyname, permissive, roles, cmd, qual, with_check FROM pg_policies
  WHERE schemaname NOT IN ('pg_catalog', 'information_schema', 'auth', 'storage', 'realtime', 'graphile_worker', 'migrations_meta')) p`;
const r = spawnSync("psql", [url, "-X", "-A", "-t", "-v", "ON_ERROR_STOP=1", "-c", q], { encoding: "utf8" });
if (r.status !== 0) { console.error(`policy-dump: psql failed: ${r.error?.message ?? r.stderr}`); process.exit(2); }

type Row = { schemaname: string; tablename: string; policyname: string; permissive: string; roles: string[]; cmd: string; qual: string | null; with_check: string | null };
const bySchema = new Map<string, string[]>();
for (const p of JSON.parse(r.stdout.trim()) as Row[]) {
  const sql = `CREATE POLICY ${p.policyname} ON ${p.schemaname}.${p.tablename}${p.permissive === "RESTRICTIVE" ? " AS RESTRICTIVE" : ""}`
    + ` FOR ${p.cmd} TO ${p.roles.join(", ")}`
    + (p.qual !== null ? `\n  USING (${p.qual})` : "") + (p.with_check !== null ? `\n  WITH CHECK (${p.with_check})` : "") + ";";
  bySchema.set(p.schemaname, [...(bySchema.get(p.schemaname) ?? []), sql]);
}
mkdirSync(out, { recursive: true });
for (const [schema, list] of bySchema)
  writeFileSync(join(out, `${schema}.sql`), `-- generated by db/tools/policy-dump.ts from pg_policies; do not edit by hand\n${list.join("\n")}\n`);
console.log(`policy-dump: ${[...bySchema.keys()].join(", ") || "no policies"} -> ${out}`);
