#!/usr/bin/env bash
# infra/ci/release-lock.sh - record image digests in releases/<env>.lock.yaml (02-TRD s12.2).
# usage: release-lock.sh <dev|staging|prod> <registry.lims.internal:5000/<repo>@sha256:<hex>>...
# Merges into the existing lock (same repo -> new digest), sorted output, atomic rename,
# serialised by a lock dir. All-or-nothing: any bad argument -> exit 2, nothing written.
# RELEASES_DIR overrides the output dir (default infra/releases).
set -euo pipefail

REG="registry.lims.internal:5000"
die() { echo "release-lock.sh: $*" >&2; exit 2; }

[ $# -ge 2 ] || die "usage: release-lock.sh <dev|staging|prod> <$REG/<repo>@sha256:<hex>>..."
env=$1; shift
case "$env" in dev|staging|prod) ;; *) die "unknown env '$env' (dev|staging|prod)";; esac

comp='[a-z0-9]+([._-][a-z0-9]+)*'
re="^registry\\.lims\\.internal:5000/(${comp}(/${comp})*)@sha256:[0-9a-f]{64}\$"
declare -A img=()
new=()
for r in "$@"; do
  [[ $r =~ $re ]] || die "not a $REG digest reference: $r"
  new+=("${BASH_REMATCH[1]}" "$r")
done

dir=${RELEASES_DIR:-"$(cd "$(dirname "$0")/.." && pwd)/releases"}
mkdir -p "$dir"
out="$dir/$env.lock.yaml"
lockd="$dir/.$env.lock.d"
tmp=""
got=""
for _ in $(seq 600); do
  if mkdir "$lockd" 2>/dev/null; then got=1; break; fi
  sleep 0.1
done
[ -n "$got" ] || die "lock busy for 60 s: $lockd (remove it if no run is active)"
trap 'rm -f "$tmp"; rmdir "$lockd"' EXIT

if [ -f "$out" ]; then
  while IFS= read -r line; do
    [[ $line =~ ^\ \ \"(.+)\":\ \"(.+)\"$ ]] && img[${BASH_REMATCH[1]}]=${BASH_REMATCH[2]}
  done < "$out"
fi
for ((i = 0; i < ${#new[@]}; i += 2)); do img[${new[i]}]=${new[i + 1]}; done

tmp=$(mktemp "$dir/.$env.lock.yaml.XXXXXX")
{
  echo "# generated by infra/ci/release-lock.sh"
  echo "env: $env"
  echo "images:"
  while IFS= read -r k; do printf '  "%s": "%s"\n' "$k" "${img[$k]}"; done \
    < <(printf '%s\n' "${!img[@]}" | LC_ALL=C sort)
} > "$tmp"
mv -f "$tmp" "$out"
tmp=""
