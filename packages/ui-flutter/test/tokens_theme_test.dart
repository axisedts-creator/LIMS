// T0D-15 / AC-0D-9.1 (Flutter side) + 04-UI-UX §8 "Theme": LimsTheme.light(accent) -> ThemeData built from tokens.g.dart.
// The regenerate==committed byte check is T0D-11's build-tokens.test.ts; here the committed Dart file is checked against
// tokens.json by an independent parse, and the theme must consume it.
import 'dart:io';

import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:lims_ui/lims_ui.dart';

import '_helpers.dart';

String _cap(String s) => s[0].toUpperCase() + s.substring(1);

void main() {
  final tok = tokensJson();
  final dart = File('${pkgDir().path}/lib/src/tokens.g.dart').readAsStringSync();

  test('AC-0D-9.1 every tone colour in tokens.json is in tokens.g.dart with the same ARGB', () {
    final tone = (tok['color'] as Map)['tone'] as Map;
    for (final t in tone.entries) {
      for (final p in (t.value as Map).entries) {
        final name = 'colorTone${_cap(t.key as String)}${_cap(p.key as String)}';
        final want = hex(p.value as String).toARGB32();
        final m = RegExp('static const Color $name = Color\\(0x([0-9A-Fa-f]{8})\\);').firstMatch(dart);
        expect(m, isNotNull, reason: '$name missing from tokens.g.dart');
        expect(int.parse(m!.group(1)!, radix: 16), want, reason: name);
      }
    }
  });

  test('tokens.g.dart keeps the generated header', () {
    expect(dart, startsWith('// GENERATED by packages/ui/scripts/build-tokens.ts'));
  });

  test('LimsTheme.light() is Material 3, light, colours from tokens', () {
    final t = LimsTheme.light();
    expect(t.useMaterial3, isTrue);
    expect(t.brightness, Brightness.light);
    expect(t.colorScheme.primary, LimsTokens.colorAccentDefault);
    expect(t.colorScheme.onPrimary, LimsTokens.colorAccentFg);
    expect(t.colorScheme.error, LimsTokens.colorToneDangerFg);
  });

  test('LimsTheme.light(accent:) overrides primary only', () {
    const a = Color(0xFF0F766E);
    final t = LimsTheme.light(accent: a);
    expect(t.colorScheme.primary, a);
    expect(t.colorScheme.error, LimsTokens.colorToneDangerFg);
  });

  // LD-140 / T0D-UI-R05: Plus Jakarta Sans replaces Noto Sans as the first family (spec 10-DESIGN-SYSTEM s5); the old
  // 'Noto Sans first' assertion contradicted the lead decision. Noto Sans stays bundled as a fallback face.
  test('fonts: Plus Jakarta Sans first, Devanagari fallback, bundled as package assets (no runtime download)', () {
    final t = LimsTheme.light();
    expect(t.textTheme.bodyMedium!.fontFamily, 'Plus Jakarta Sans');
    expect(t.textTheme.bodyMedium!.fontFamilyFallback, contains('Noto Sans Devanagari'));
    final pub = File('${pkgDir().path}/pubspec.yaml').readAsStringSync();
    for (final f in ['Plus Jakarta Sans', 'Noto Sans', 'Noto Sans Devanagari', 'Noto Sans Mono']) {
      expect(pub, contains('family: $f'), reason: 'font family $f declared');
    }
    final assets = RegExp(r'asset:\s*(\S+)').allMatches(pub).map((m) => m.group(1)!).toList();
    expect(assets, isNotEmpty);
    for (final a in assets) {
      expect(File('${pkgDir().path}/$a').existsSync(), isTrue, reason: 'font asset $a missing');
    }
  });

  test('tap targets padded to Material minimum (48dp)', () {
    expect(LimsTheme.light().materialTapTargetSize, MaterialTapTargetSize.padded);
  });
}
