// tokens/tokens.json -> dist/tokens.css, src/tokens.ts, ../ui-flutter/lib/src/tokens.g.dart (02-TRD §UI build).
// Runs with `node scripts/build-tokens.ts` (native type stripping). Deterministic: same input, same bytes.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

type Leaf = string | number;
type Tree = { [k: string]: Leaf | Tree };

const ui = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(ui, 'tokens', 'tokens.json'), 'utf8')) as Tree;
const HEX = /^#[0-9A-F]{6}$/i;
const ALIAS = /^\{([\w.]+)\}$/;

function lookup(path: string, depth = 0): Leaf {
  let node: Leaf | Tree | undefined = tokens;
  for (const k of path.split('.')) node = typeof node === 'object' ? node[k] : undefined;
  if (node === undefined || typeof node === 'object') throw new Error(`unknown token ${path}`);
  const m = typeof node === 'string' ? ALIAS.exec(node) : null;
  if (!m?.[1]) return node;
  if (depth > 5) throw new Error(`alias loop at ${path}`);
  return lookup(m[1], depth + 1);
}

const leaves: [string[], Leaf][] = [];
(function walk(node: Tree, path: string[]): void {
  for (const [k, v] of Object.entries(node)) {
    if (typeof v === 'object') walk(v, [...path, k]);
    else leaves.push([[...path, k], lookup([...path, k].join('.'))]);
  }
})(tokens, []);

for (const [p, v] of leaves)
  if (typeof v === 'string' && /url\(|https?:|[;{}<>]/i.test(v)) throw new Error(`unsafe token value at ${p.join('.')}`);

// CSS: color.accent.default -> --lims-accent; color.neutral.0 -> --lims-neutral-0; space.0_5 -> --lims-space-0-5
const cssName = (p: string[]): string => {
  const q = p[0] === 'color' ? p.slice(1) : p;
  const r = q.at(-1) === 'default' ? q.slice(0, -1) : q;
  return '--lims-' + r.join('-').replace(/[^A-Za-z0-9-]/g, '-').replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
};
const pxGroups = new Set(['space', 'radius', 'breakpoint', 'touchTarget']);
const cssValue = (p: string[], v: Leaf): string => {
  if (typeof v === 'string') return HEX.test(v) ? v.toUpperCase() : v;
  if (p[0] === 'motion') return `${v}ms`;
  if (pxGroups.has(p[0] ?? '') || (p[0] === 'font' && p[1] === 'size')) return `${v}px`;
  return String(v);
};
const css =
  '/* GENERATED by scripts/build-tokens.ts from tokens/tokens.json. Do not edit. */\n:root {\n' +
  leaves.map(([p, v]) => `  ${cssName(p)}: ${cssValue(p, v)};\n`).join('') +
  '}\n@media (prefers-reduced-motion: reduce) {\n  :root {\n' +
  leaves.filter(([p]) => p[0] === 'motion' && p[1] === 'duration').map(([p]) => `    ${cssName(p)}: 0ms;\n`).join('') +
  '  }\n}\n';

// TS: resolved tree, aliases replaced by values.
const resolved = (node: Tree, path: string[]): Tree =>
  Object.fromEntries(
    Object.entries(node).map(([k, v]) => [k, typeof v === 'object' ? resolved(v, [...path, k]) : lookup([...path, k].join('.'))]),
  );
const ts =
  '// GENERATED by scripts/build-tokens.ts from tokens/tokens.json. Do not edit.\n' +
  `export const tokens = ${JSON.stringify(resolved(tokens, []), null, 2)} as const;\n`;

// Dart: color.neutral.0 -> colorNeutral0; space.0_5 -> space0x5; font.size.2xl.size -> fontSize2xlSize
const dartName = (p: string[]): string =>
  p.map((s, i) => (i === 0 ? s : s.charAt(0).toUpperCase() + s.slice(1)).replace(/_/g, 'x')).join('');
const dartLine = (p: string[], v: Leaf): string => {
  const n = dartName(p);
  if (typeof v === 'number') return `  static const double ${n} = ${Number.isInteger(v) ? v.toFixed(1) : v};\n`;
  if (HEX.test(v)) return `  static const Color ${n} = Color(0xFF${v.slice(1).toUpperCase()});\n`;
  return `  static const String ${n} = '${v.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}';\n`;
};
const dart =
  '// GENERATED by packages/ui/scripts/build-tokens.ts from packages/ui/tokens/tokens.json. Do not edit.\n' +
  "import 'dart:ui' show Color;\n\n" +
  'abstract final class LimsTokens {\n' +
  leaves.map(([p, v]) => dartLine(p, v)).join('') +
  '}\n';

const out = (rel: string, body: string): void => {
  const f = join(ui, rel);
  mkdirSync(dirname(f), { recursive: true });
  writeFileSync(f, body);
};
out('dist/tokens.css', css);
out('src/tokens.ts', ts);
out('../ui-flutter/lib/src/tokens.g.dart', dart);
