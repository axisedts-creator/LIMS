// Port registry (02-TRD §6.3, 03-APP-FLOW §3.4, AC-0D-6.1/6.2/6.4, AB-15, 08 A19 P-46). Same function serves API and worker boot.
// Resolution per port: real (owner loaded) > forced fake (dev/ci) > fake (dev/ci) > listed phase stub (staging/production) > boot failure.
import { LimsError } from '../errors.js';
import { PORT_OWNERS } from '../module.js';
import { PHASE_STUBS } from './phase-stubs.js';

export interface PortLog {
  debug(o: Record<string, unknown>, m?: string): void;
  info(o: Record<string, unknown>, m?: string): void;
  warn(o: Record<string, unknown>, m?: string): void;
  error(o: Record<string, unknown>, m?: string): void;
}
export interface PortMetrics {
  setGauge(name: string, v: number): void;
  inc(name: string, labels?: Record<string, string>, by?: number): void;
}
export type PortResolution = 'real' | 'fake' | 'stub';
export type PortRegistry = Readonly<Record<string, unknown>>;

export interface ResolvePortsOpts {
  readonly env: string;
  readonly modules: ReadonlyArray<{ readonly name: string; readonly ports?: Readonly<Record<string, unknown>> }>;
  /** LIMS_CORE_FAKE_PORTS (dev/ci only). */
  readonly forceFake?: readonly string[];
  readonly fakes: Readonly<Record<string, unknown>>;
  readonly stubs: Readonly<Record<string, unknown>>;
  readonly phaseStubs?: readonly string[];
  readonly owners?: Readonly<Record<string, string>>;
  /** PORT_CONSUMERS (generated by T0C gen-port-consumers). Required: no default, an absent list must not mean "open". */
  readonly consumers: Readonly<Record<string, readonly string[]>>;
  readonly log: PortLog;
  readonly metrics: PortMetrics;
}

const LENIENT_ENVS = new Set(['dev', 'ci']);
const has = (o: object, k: string): boolean => Object.hasOwn(o, k);

export function resolvePorts(opts: ResolvePortsOpts): {
  resolution: Readonly<Record<string, PortResolution>>;
  portsFor(module: string): PortRegistry;
} {
  const { env, modules, forceFake = [], fakes, stubs, phaseStubs = PHASE_STUBS, owners = PORT_OWNERS, consumers, log, metrics } = opts;
  const lenient = LENIENT_ENVS.has(env);
  const errors: string[] = [];

  // Module exports: known port, owned by the exporter, exported once.
  const realImpl = new Map<string, unknown>();
  for (const m of modules) {
    for (const [port, impl] of Object.entries(m.ports ?? {})) {
      if (!has(owners, port)) errors.push(`module ${m.name} exports unknown port ${port}`);
      else if (owners[port] !== m.name) errors.push(`module ${m.name} exports ${port}, owned by ${owners[port]}`);
      else if (realImpl.has(port)) errors.push(`${port} exported by more than one module`);
      else realImpl.set(port, impl);
    }
  }

  const forced = new Set(forceFake);
  for (const p of forced) {
    if (!has(owners, p)) errors.push(`LIMS_CORE_FAKE_PORTS names unknown port ${p}`);
    else if (!lenient) errors.push(`LIMS_CORE_FAKE_PORTS ${p} not allowed in ${env} (dev/ci only)`);
  }

  const listedStubs = new Set(phaseStubs);
  const resolution: Record<string, PortResolution> = {};
  const impls = new Map<string, unknown>();
  for (const port of Object.keys(owners)) {
    if (lenient && (forced.has(port) || !realImpl.has(port))) {
      if (!has(fakes, port)) { errors.push(`${port}: no fake available`); continue; }
      resolution[port] = 'fake';
      impls.set(port, fakes[port]);
    } else if (realImpl.has(port)) {
      resolution[port] = 'real';
      impls.set(port, realImpl.get(port));
    } else if (listedStubs.has(port) && has(stubs, port)) {
      resolution[port] = 'stub';
      impls.set(port, stubs[port]);
    } else {
      errors.push(`${port}: owner module ${owners[port]} not loaded and no listed phase stub (${env})`);
    }
  }
  if (errors.length) throw new Error(`port registry boot failed: ${errors.join('; ')}`);

  const fakeCount = Object.values(resolution).filter((r) => r === 'fake').length;
  const stubCount = Object.values(resolution).filter((r) => r === 'stub').length;
  for (const [port, r] of Object.entries(resolution)) {
    if (r === 'fake') log.warn({ event: 'fake_port_active', port, forced: forced.has(port) }, 'fake port active');
  }
  metrics.setGauge('lims_core_fake_ports_active', fakeCount);
  metrics.setGauge('lims_core_phase_stub_ports_active', stubCount);
  Object.freeze(resolution);

  const production = env === 'production';
  function portsFor(module: string): PortRegistry {
    const view: Record<string, unknown> = {};
    for (const [port, impl] of impls) {
      Object.defineProperty(view, port, {
        enumerable: true,
        configurable: false,
        get() {
          if (consumers[port]?.includes(module)) return impl;
          log.error({ event: 'port_consumer_not_listed', module, port }, 'port read by a module not in PORT_CONSUMERS');
          if (production) {
            metrics.inc('lims_core_port_consumer_not_listed_total', { module, port });
            return impl;
          }
          throw new LimsError('common.internal'); // no detail: the consumer list stays server-side
        },
      });
    }
    return Object.freeze(view);
  }

  return { resolution, portsFor };
}
