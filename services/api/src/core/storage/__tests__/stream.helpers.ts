// T0B-FILESTREAM-1 (LD-312) shared fakes: a raw Storage service that can STREAM (getStream / putStream), generated objects that are never held
// in memory, call and byte counters, and a retained-memory probe. Synthetic data only.
// Prescribed raw API (RawStorage, optional members):
//   getStream(bucket, key, o?: { range?: { start: number; end: number } /* inclusive */ }) -> { body: Readable | web ReadableStream | AsyncIterable<Uint8Array>; size: number /* WHOLE object */; etag?: string; lastModified?: Date }
//   putStream(bucket, key, body: AsyncIterable<Uint8Array>, o: { contentType: string; ifAbsent?: boolean; byteSize?: number }) -> void
// Prescribed adapter API (StorageAdapter): readStream(bucket, path, o?: { range?: { start; end } }) -> { body: Readable; byteSize; etag?; lastModified?; range?: { start; end } }
//                                           putStream(bucket, path, source, { contentType, ifAbsent?, maxBytes? }) -> { sha256, byteSize }
import { createHash } from 'node:crypto';
import { Readable } from 'node:stream';
import v8 from 'node:v8';
import vm from 'node:vm';
import { KEY_FILE, CREDENTIAL, TENANT_A, recorders } from './helpers.js';

export const MiB = 1024 * 1024;
export const CHUNK = 64 * 1024;
/** Slack for what a source may have produced ahead of the consumer (stream buffers): 4 chunks. */
export const SLACK = 4 * CHUNK;

/** Deterministic content: byte at position p. A generated object of any size is described by its length only. */
export const patternByte = (p: number): number => (p * 31 + 7) & 255;
export function bytesOf(start: number, len: number, prefix?: Uint8Array): Buffer {
  const b = Buffer.allocUnsafe(len);
  for (let i = 0; i < len; i++) { const p = start + i; b[i] = prefix && p < prefix.length ? prefix[p]! : patternByte(p); }
  return b;
}
export const sha256 = (b: Uint8Array): string => createHash('sha256').update(b).digest('hex');
/** sha256 of the generated object, computed chunk by chunk (never holds the object). */
export function expectedSha(total: number, prefix?: Uint8Array): string {
  const h = createHash('sha256');
  for (let pos = 0; pos < total; pos += CHUNK) h.update(bytesOf(pos, Math.min(CHUNK, total - pos), prefix));
  return h.digest('hex');
}

export interface Pulled { bytes: number; chunks: number }
/** Lazily generated byte source [start, start+len) of the pattern object; `pulled` counts what was really produced. */
export function source(len: number, o: { start?: number; prefix?: Uint8Array; pulled?: Pulled; failAfter?: number; failMessage?: string } = {}): Readable {
  const start = o.start ?? 0; const pulled = o.pulled ?? { bytes: 0, chunks: 0 };
  async function* gen(): AsyncGenerator<Buffer> {
    for (let done = 0; done < len; done += CHUNK) {
      if (o.failAfter !== undefined && done >= o.failAfter) throw new Error(o.failMessage ?? 'connection reset');
      const n = Math.min(CHUNK, len - done);
      pulled.bytes += n; pulled.chunks += 1;
      yield bytesOf(start + done, n, o.prefix);
    }
  }
  return Readable.from(gen(), { objectMode: false, highWaterMark: CHUNK });
}

export interface StoredObj { size: number; etag?: string; lastModified?: Date; contentType?: string; bytes?: Buffer; sha256?: string; prefix?: Uint8Array }
const RETAIN_LIMIT = 4 * MiB;

export function streamRaw() {
  const objects = new Map<string, StoredObj>();
  const calls: string[] = [];
  const gets: Array<{ bucket: string; key: string; range?: { start: number; end: number } }> = [];
  const pulled: Pulled = { bytes: 0, chunks: 0 };
  const putBytes: Pulled = { bytes: 0, chunks: 0 };
  const state: { failAfter?: number; failMessage?: string; noEtag?: boolean } = {};
  const k = (b: string, p: string) => `${b}|${p}`;
  const raw = {
    async put(b: string, p: string, bytes: Uint8Array, o: { contentType: string; ifAbsent?: boolean }) {
      calls.push('put');
      if (o.ifAbsent && objects.has(k(b, p))) throw new Error('already exists');
      objects.set(k(b, p), { size: bytes.length, bytes: Buffer.from(bytes), contentType: o.contentType, sha256: sha256(bytes) });
    },
    async get(b: string, p: string) {
      calls.push('get'); const o = objects.get(k(b, p)); if (!o) throw new Error('not found');
      return new Uint8Array(o.bytes ?? bytesOf(0, o.size, o.prefix));
    },
    async move(b: string, from: string, to: string) { calls.push('move'); const o = objects.get(k(b, from)); if (!o) throw new Error('not found'); objects.delete(k(b, from)); objects.set(k(b, to), o); },
    async remove(b: string, p: string) { calls.push('remove'); objects.delete(k(b, p)); },
    async sign() { calls.push('sign'); return 'https://storage.invalid/sign/never-used?token=never'; },
    async head(b: string, p: string) {
      calls.push('head'); const o = objects.get(k(b, p)); if (!o) return undefined;
      return { byteSize: o.size, contentType: o.contentType ?? 'application/octet-stream', ...(o.sha256 ? { sha256: o.sha256 } : {}), ...(o.etag ? { etag: o.etag } : {}), ...(o.lastModified ? { lastModified: o.lastModified } : {}) };
    },
    async getStream(b: string, p: string, g: { range?: { start: number; end: number } } = {}) {
      calls.push('getStream'); gets.push({ bucket: b, key: p, ...(g.range ? { range: g.range } : {}) });
      const o = objects.get(k(b, p)); if (!o) throw new Error('not found');
      const start = g.range?.start ?? 0; const len = (g.range ? g.range.end - g.range.start + 1 : o.size);
      const body = o.bytes
        ? Readable.from([o.bytes.subarray(start, start + len)], { objectMode: false })
        : source(len, { start, pulled, ...(o.prefix ? { prefix: o.prefix } : {}), ...(state.failAfter !== undefined ? { failAfter: state.failAfter, failMessage: state.failMessage ?? '' } : {}) });
      if (o.bytes) pulled.bytes += len;
      return { body, size: o.size, ...(o.etag ? { etag: o.etag } : {}), ...(o.lastModified ? { lastModified: o.lastModified } : {}) };
    },
    async putStream(b: string, p: string, body: AsyncIterable<Uint8Array>, o: { contentType: string; ifAbsent?: boolean; byteSize?: number }) {
      calls.push('putStream');
      if (o.ifAbsent && objects.has(k(b, p))) throw new Error('already exists');
      const h = createHash('sha256'); const keep: Buffer[] = []; let size = 0;
      for await (const c of body) {
        const buf = Buffer.from(c); h.update(buf); size += buf.length; putBytes.bytes += buf.length; putBytes.chunks += 1;
        if (size <= RETAIN_LIMIT) keep.push(buf); else keep.length = 0;
      }
      objects.set(k(b, p), { size, contentType: o.contentType, sha256: h.digest('hex'), ...(size <= RETAIN_LIMIT ? { bytes: Buffer.concat(keep) } : {}) });
    },
  };
  return {
    raw, objects, calls, gets, pulled, putBytes, state, connect: () => raw,
    /** Registers a stored object: generated by length (no bytes held) or from real bytes. */
    seed(bucket: string, path: string, o: StoredObj | Uint8Array) { objects.set(k(bucket, path), o instanceof Uint8Array ? { size: o.length, bytes: Buffer.from(o), sha256: sha256(o) } : o); },
    has: (bucket: string, path: string) => objects.has(k(bucket, path)),
    stored: (bucket: string, path: string) => objects.get(k(bucket, path)),
    count: (op: string) => calls.filter((c) => c === op).length,
  };
}
export type StreamRaw = ReturnType<typeof streamRaw>;

/** The REAL core storage adapter over the streaming fake raw service. */
export async function makeStreamStorage(module = 'reporting', tenantId = TENANT_A) {
  const f = streamRaw(); const r = recorders();
  const { createStorage } = await import('../index.js');
  const storage: any = createStorage({
    env: { LIMS_CORE_STORAGE_KEY_FILE: KEY_FILE }, readFile: (p: string) => (p === KEY_FILE ? `${CREDENTIAL}\n` : (() => { throw new Error('ENOENT'); })()),
    connect: f.connect, module, tenantId, log: r.log, metrics: r.metrics,
  } as any);
  return { f, r, storage };
}

// ---------------------------------------------------------------------------------------------------- retained memory probe
const gc: () => void = (() => { try { v8.setFlagsFromString('--expose-gc'); return vm.runInNewContext('gc') as () => void; } catch { return () => undefined; } })();
const used = (): number => { const m = process.memoryUsage(); return m.heapUsed + m.arrayBuffers; };
/** Retained heap + Buffer memory above the baseline taken at construction. sample() forces a collection first, so garbage is not counted, only what is still held. */
export function memProbe() {
  gc(); const base = used(); let peak = base;
  return { sample() { gc(); peak = Math.max(peak, used()); }, growth: () => peak - base, growthMiB: () => (peak - base) / MiB };
}

/** Reads a body (Readable / web stream / async iterable / bytes) to its end, hashing as it goes; keeps nothing. */
export async function sink(body: unknown, probe?: ReturnType<typeof memProbe>): Promise<{ size: number; sha256: string }> {
  const h = createHash('sha256'); let size = 0; let n = 0;
  const feed = (c: Uint8Array) => { h.update(c); size += c.length; if (probe && ++n % 32 === 0) probe.sample(); };
  const b: any = body;
  if (b instanceof Uint8Array) feed(b);
  else if (typeof b?.getReader === 'function') { const rd = b.getReader(); for (;;) { const { done, value } = await rd.read(); if (done) break; feed(value); } }
  else if (typeof b?.[Symbol.asyncIterator] === 'function') { for await (const c of b) feed(typeof c === 'string' ? Buffer.from(c) : c); }
  else throw new Error('body is not bytes, a web stream or an async iterable');
  probe?.sample();
  return { size, sha256: h.digest('hex') };
}
