// C16.T-SEC1 — table probes, static part (07-SECURITY §6.2 "every engagement table", "CI asserts no DELETE grant except on the read-model tables"; 05-SCHEMA §1 inventory, §3 DDL, §5.2 policy matrix).
// The engagement DDL is not in db/migrations yet (C0 writes it from 05-SCHEMA), so the live SQL probes are db/tests/engagement/T-SEC1_table_probes.test.sql (needs the migrated database; not part of verify.cmd).
// This file keeps the SPEC self-consistent so that DDL generated from it is probe-complete: every table is tenant-scoped, has a policy row for each command it is granted, and DELETE is granted only where the spec allows.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { REPO_ROOT } from '../../../../core/module.js';

const MD = readFileSync(join(REPO_ROOT, 'spec/chunks/C16-patient-engagement/05-SCHEMA.md'), 'utf8').replace(/\r\n/g, '\n');
const section = (from: string, to: string) => MD.slice(MD.indexOf(from), MD.indexOf(to));
const INVENTORY = section('## 1. Table inventory', '## 2. Notable columns');
const DDL = section('## 3. DDL', '## 4. Guard triggers');
const MATRIX = section('### 5.2 Policy matrix', '### 5.3 Policy SQL');

interface Inv { table: string; cls: string; scope: string; grants: string[] }
const inventory: Inv[] = INVENTORY.split('\n').filter((l) => /^\| `/.test(l)).flatMap((l) => {
  const c = l.split('|').map((x) => x.trim());
  const names = [...c[1]!.matchAll(/`([a-z_]+)`/g)].map((m) => m[1]!);
  return names.map((table) => ({ table, cls: c[2]!, scope: c[3]!, grants: c[5]!.split(/\s+/).filter(Boolean) }));
});
const ddlTables = [...DDL.matchAll(/CREATE TABLE engagement\.([a-z_]+)/g)].map((m) => m[1]!);
const ddlBlock = (t: string) => { const i = DDL.indexOf(`CREATE TABLE engagement.${t} `); const j = DDL.indexOf('CREATE TABLE engagement.', i + 10); return DDL.slice(i, j < 0 ? undefined : j); };
/** policy matrix: table -> [S, I, U, D] cells; grouped rows ("a, b", "cs_*") are expanded onto their members. */
const matrix = new Map<string, string[]>();
for (const l of MATRIX.split('\n').filter((x) => /^\| [a-z_*, ]+ \|/.test(x))) {
  const c = l.split('|').map((x) => x.trim());
  const names = c[1]!.split(',').map((x) => x.trim());
  for (const n of names) {
    if (n.endsWith('*')) inventory.filter((i) => i.table.startsWith(n.slice(0, -1)) && !i.table.startsWith('g_')).forEach((i) => matrix.set(i.table, [c[2]!, c[3]!, c[4]!, c[5]!]));
    else matrix.set(n, [c[2]!, c[3]!, c[4]!, c[5]!]);
  }
}
const tenantTables = inventory.filter((i) => !i.table.startsWith('g_'));
const ddlTenantTables = tenantTables.filter((i) => i.table !== 'event_inbox');

describe('05-SCHEMA inventory vs DDL (every table is probed)', () => {
  it('parses the inventory (40 tables incl. 3 global coded sets and the C0-generated event_inbox)', () => {
    expect(inventory).toHaveLength(40);
    expect(inventory.filter((i) => i.table.startsWith('g_'))).toHaveLength(3);
  });

  it('inventory and CREATE TABLE statements list exactly the same tables', () => {
    // event_inbox is generated by C0 (03-IC §12), not written in 05-SCHEMA §3
    expect([...ddlTables].sort()).toEqual(inventory.map((i) => i.table).filter((t) => t !== 'event_inbox').sort());
  });

  it('every non-global table has a tenant_id column; centre-scoped tables also centre_id (the columns the probes bind)', () => {
    for (const i of ddlTenantTables) {
      const b = ddlBlock(i.table);
      expect(/\btenant_id\b/.test(b), `${i.table} tenant_id`).toBe(true);
      if (i.scope.includes('centre')) expect(/\bcentre_id\b/.test(b), `${i.table} centre_id`).toBe(true);
    }
  });

  it('global coded sets have no tenant_id and grant SELECT only', () => {
    for (const i of inventory.filter((x) => x.table.startsWith('g_'))) { expect(/\btenant_id\b/.test(ddlBlock(i.table)), i.table).toBe(false); expect(i.grants, i.table).toEqual(['S']); }
  });

  it('every composite foreign key carries tenant_id first (no cross-tenant reference can be formed)', () => {
    const bad = [...DDL.matchAll(/FOREIGN KEY \(([^)]*)\)/g)].map((m) => m[1]!).filter((cols) => !/^\s*tenant_id\b/.test(cols));
    expect(bad).toEqual([]);
  });
});

describe('policy matrix (05-SCHEMA §5.2) vs grants', () => {
  it('every tenant table has a policy row', () => {
    expect(tenantTables.filter((i) => !matrix.has(i.table)).map((i) => i.table)).toEqual([]);
  });

  it('a command is granted iff the matrix has a policy for it: S, I, U cells are non-empty exactly where the grant letter exists; D cell is "—" unless D granted', () => {
    const bad: string[] = [];
    for (const i of tenantTables) {
      const row = matrix.get(i.table);
      if (!row) continue;
      (['S', 'I', 'U', 'D'] as const).forEach((letter, k) => {
        const hasPolicy = row[k] !== '—' && row[k] !== '';
        if (i.grants.includes(letter) !== hasPolicy) bad.push(`${i.table}: grant ${letter}=${i.grants.includes(letter)} but policy cell "${row[k]}"`);
      });
    }
    expect(bad).toEqual([]);
  });

  it('DELETE is granted to lims_app only on the 8 class-E tables; the four read models are among them', () => {
    const withD = inventory.filter((i) => i.grants.includes('D')).map((i) => i.table).sort();
    expect(withD).toEqual(['link_codes', 'notifications', 'number_counters', 'otp_challenges', 'patient_order_specimens', 'patient_orders', 'patient_reports', 'smart_summaries']);
    for (const i of inventory.filter((x) => x.grants.includes('D'))) expect(i.cls.startsWith('E'), `${i.table} class ${i.cls}`).toBe(true);
  });

  it('every DELETE policy admits only the system actor (SYS ...), never staff or patient', () => {
    for (const i of inventory.filter((x) => x.grants.includes('D'))) expect(matrix.get(i.table)![3], i.table).toMatch(/^SYS\b/);
  });

  it('patient-visible tables have no STAFF-only wide policy leaking to patients and staff have no policy on read models (AB-13: staff read patient read models -> zero rows)', () => {
    for (const t of ['patient_orders', 'patient_order_specimens', 'patient_reports', 'smart_summaries']) {
      const [s, i, u] = matrix.get(t)!;
      expect(s, `${t} S`).not.toMatch(/STAFF/);
      expect(`${i} ${u}`, `${t} I/U`).not.toMatch(/STAFF|PAT_/);
    }
  });

  it('no patient policy writes staff-only or system-only tables: settings, slot_templates, slot_blackouts, queue_*, reminders, membership_plans, bookable_items have no PAT_ write policy', () => {
    for (const t of ['settings', 'slot_templates', 'slot_blackouts', 'queue_definitions', 'queue_counters', 'queue_day_counters', 'queue_tokens', 'queue_displays', 'reminders', 'membership_plans', 'patient_memberships', 'bookable_items', 'booking_centres']) {
      const [, i, u] = matrix.get(t)!;
      const writes = `${i} ${u}`.replace(/DISP \(`id = app\.current_actor_id\(\)`[^)]*\)/g, '');
      expect(writes, `${t} I/U`).not.toMatch(/PAT_/);
    }
  });

  it('display devices have SELECT only on the board tables, plus a self-row update on queue_displays', () => {
    const disp = [...matrix.entries()].filter(([, r]) => /DISP/.test(r.join(' '))).map(([t]) => t).sort();
    expect(disp).toEqual(['booking_centres', 'queue_counters', 'queue_definitions', 'queue_day_counters', 'queue_displays', 'queue_tokens'].sort());
    for (const [t, r] of matrix) { if (/DISP/.test(`${r[1]} ${r[3]}`)) throw new Error(`${t}: DISP must not insert or delete`); if (/DISP/.test(r[2]!) && t !== 'queue_displays') throw new Error(`${t}: DISP may update only queue_displays`); }
  });
});
