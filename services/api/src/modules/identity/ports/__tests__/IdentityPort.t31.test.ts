// T31 IdentityPort patient-context methods (08 s4.14 / A28.2; 03-APP-FLOW s3.5a; 05-SCHEMA s4.1; 07-SECURITY AU-T13/AU-T16; LD-81 lifts the D-218 GoTrue block for the patient kind).
// LD-81 (2026-11-09): the patient access JWT is issued by LIMS (no GoTrue call / refresh token / session for kind patient); openPatientSession mints it. The nine added methods'
// T5 contract cases stay in IdentityPort.c2.test.ts / IdentityPort.contract.test.ts; this file pins the T31 delta: provisionPatientMembership, openPatientSession and
// revokePatientSessions({ deactivateMembership: true }) no longer fail closed.
// Seams (the writer must match them or raise a dispute) - createIdentityPort deps gain:
//     newToken?: () => string                    (default: 32 random bytes base64url = 43 chars)
//     mintPatientAccessToken(c: { sub, sessionId, aal, issuedAt: Date, expiresAt: Date }) => string       (EdDSA signer; claims exactly sub / session_id / aal / exp / iat)
//     newId?: () => string
//   CoreAdminRepo gains (all take ctx first, bind tenant_id = ctx.tenantId, run in ctx.tx):
//     createPatientMembership(ctx, { accountId }) -> { membershipId, userId }       idempotent per accountId; the user id is generated by LIMS (core.users.id); no phone / e-mail stored
//     insertPatientSession(ctx, s)                s = { id, membershipId, userId, kind: 'patient', tokenSha256: Buffer, state: 'active', aal: 'aal1', appInstanceId, appPlatform,
//                                                      idleTimeoutMinutes, idleExpiresAt, absoluteExpiresAt, expiresAt, actorId }; NO gotrueSessionId / refresh / access token fields
//     deactivatePatientMembership(ctx, { membershipId })                             (the A28.2 identity-system-actor write scope lives inside the repo)
// Expected now: provision / open fail with common.internal blocked_gotrue_t1; deactivateMembership=true fails with blocked_a28_2.
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it, vi } from 'vitest';
import { createIdentityPort } from '../IdentityPort.impl.js';
import { makeFakeRepo, makeCtx, member, mid, actorIdFor } from './helpers';

const NOW = 1_000_000, H = 3_600_000, D = 86_400_000;
const APP = '01900000-0000-7000-8000-0000000f0001', ACCOUNT = '01900000-0000-7000-8000-0000000f0002';
const code = async (p: Promise<unknown>) => (await p.then(() => undefined, (e: any) => e))?.code;
const sha = (s: string) => createHash('sha256').update(s).digest();

function setup() {
  const f = makeFakeRepo({ members: [member('A', 'pt', 20, { actorType: 'patient', roleCodes: [] }), member('A', 'ptoff', 21, { actorType: 'patient', roleCodes: [], status: 'deactivated' }),
    member('A', 'admin', 2, { roleCodes: ['tenant_admin'] }), member('B', 'pt', 30, { actorType: 'patient', roleCodes: [] })] });
  const inserted: any[] = []; const created: any[] = []; const deactivated: any[] = []; const order: string[] = [];
  const accounts = new Map<string, { membershipId: string; userId: string }>();
  const repo: any = { ...f.repo,
    async createPatientMembership(_ctx: any, i: any) { created.push(i); order.push('create'); if (!accounts.has(i.accountId)) accounts.set(i.accountId, { membershipId: mid(20), userId: mid(20 + 0x1000) }); return accounts.get(i.accountId)!; },
    async insertPatientSession(_ctx: any, s: any) { inserted.push(s); order.push('insert'); },
    async deactivatePatientMembership(_ctx: any, i: any) { deactivated.push(i); order.push('deactivate'); },
    async revokeSessions(ctx: any, i: any) { order.push('revoke'); return f.repo.revokeSessions(ctx, i); },
  };
  const mint = vi.fn((c: any) => `PAT-JWT.${c.sessionId}`);
  let n = 0; const port = createIdentityPort({ repo, systemActorPermissions: () => [], nowMs: () => NOW, newToken: () => `P${(0x100 + n++).toString(36).padStart(42, '0')}`, newId: () => `01900000-0000-7000-8000-${(0xaa00 + n++).toString(16).padStart(12, '0')}`,
    mintPatientAccessToken: mint } as any);
  const preAuth = (tenant: 'A' | 'B' = 'A', persona = 'pre') => { const ctx = makeCtx(tenant, 'patient', persona); f.st.claims.set(ctx.actor.id, { aal: 'aal1', patient_stage: 'pre_auth' }); return ctx; };
  return { ...f, port, inserted, created, deactivated, order, mint, preAuth, repo };
}
const OPEN = { membershipId: mid(20) as any, appInstanceId: APP as any, appPlatform: 'android' as const };

describe('openPatientSession (LD-81: LIMS mints the patient access JWT; no GoTrue)', () => {
  it('pre_auth patient caller -> { sessionToken (opaque 256-bit), accessToken, accessExpiresAt = now + 1 h, sessionExpiresAt = now + 30 d }; ONE kind=patient row: aal1, idle 14 d, no GoTrue / refresh / access-token fields', async () => {
    const s = setup(); const r = await s.port.openPatientSession(s.preAuth(), OPEN);
    expect(Object.keys(r).sort()).toEqual(['accessExpiresAt', 'accessToken', 'sessionExpiresAt', 'sessionToken']);
    expect(r.sessionToken).toMatch(/^[A-Za-z0-9_-]{43}$/);
    expect(r.accessExpiresAt).toBe(new Date(NOW + H).toISOString()); expect(r.sessionExpiresAt).toBe(new Date(NOW + 30 * D).toISOString());
    expect(s.inserted).toHaveLength(1);
    const row = s.inserted[0];
    expect(row).toMatchObject({ kind: 'patient', membershipId: mid(20), userId: mid(20 + 0x1000), state: 'active', aal: 'aal1', appInstanceId: APP, appPlatform: 'android', idleTimeoutMinutes: 20160 });
    expect(Buffer.from(row.tokenSha256).equals(sha(r.sessionToken))).toBe(true);
    expect(row.idleExpiresAt).toEqual(new Date(NOW + 14 * D)); expect(row.absoluteExpiresAt).toEqual(new Date(NOW + 30 * D));
    for (const k of ['gotrueSessionId', 'refreshToken', 'accessToken', 'refreshTokenEnc', 'accessTokenEnc', 'encKeyId']) expect(row[k] ?? null, k).toBeNull();   // CHECK ties NULL to the kind
    expect(JSON.stringify(row)).not.toContain(r.sessionToken);   // only the hash is persisted
  });
  it('the access JWT is minted for (sub = the membership user id, session_id = the new row id, aal1), exp = iat + 1 h, claims exactly those five; accessToken is that string', async () => {
    const s = setup(); const r = await s.port.openPatientSession(s.preAuth(), OPEN);
    expect(s.mint).toHaveBeenCalledTimes(1); const c = s.mint.mock.calls[0]![0];
    expect(Object.keys(c).sort()).toEqual(['aal', 'expiresAt', 'issuedAt', 'sessionId', 'sub']);
    expect(c).toMatchObject({ sub: mid(20 + 0x1000), sessionId: s.inserted[0].id, aal: 'aal1' }); expect(c.expiresAt.getTime() - c.issuedAt.getTime()).toBe(H);
    expect(r.accessToken).toBe(s.mint.mock.results[0]!.value);
  });
  it('the session row is written before the token is returned and the minted token cannot outlive the session', async () => {
    const s = setup(); await s.port.openPatientSession(s.preAuth(), OPEN); expect(s.order).toEqual(['insert']);
    const c = s.mint.mock.calls[0]![0]; expect(c.expiresAt.getTime()).toBeLessThanOrEqual(s.inserted[0].absoluteExpiresAt.getTime());
  });
  it('membership must be an ACTIVE patient membership of the ctx tenant: staff / unknown / other-tenant -> common.not_found, deactivated -> identity.membership_inactive; NO row written, nothing minted', async () => {
    const s = setup();
    for (const [id, c] of [[mid(2), 'common.not_found'], [mid(99), 'common.not_found'], [mid(30), 'common.not_found'], [mid(21), 'identity.membership_inactive']] as const) {
      expect(await code(s.port.openPatientSession(s.preAuth(), { ...OPEN, membershipId: id as any })), id).toBe(c);
    }
    expect(s.inserted).toHaveLength(0); expect(s.mint).not.toHaveBeenCalled();
  });
  it('input validation: appPlatform outside android|ios, non-uuid appInstanceId / membershipId -> common.validation_failed, nothing written', async () => {
    const s = setup();
    for (const bad of [{ appPlatform: 'windows' }, { appPlatform: undefined }, { appInstanceId: 'x' }, { membershipId: 'x' }, { appInstanceId: undefined }]) {
      expect(await code(s.port.openPatientSession(s.preAuth(), { ...OPEN, ...bad } as any)), JSON.stringify(bad)).toBe('common.validation_failed');
    }
    expect(s.inserted).toHaveLength(0);
  });
  it('caller restriction stays: staff user, partner, system, and a patient that is NOT in pre_auth -> auth.forbidden; tenant B pre_auth cannot open a tenant A membership', async () => {
    const s = setup(); const post = makeCtx('A', 'patient', 'post'); s.st.claims.set(post.actor.id, { aal: 'aal1', membership_id: mid(20), session_state: 'active' });
    for (const ctx of [makeCtx('A', 'user', 'admin'), makeCtx('A', 'partner', 'p'), makeCtx('A', 'system', 'default'), post]) expect(await code(s.port.openPatientSession(ctx, OPEN))).toBe('auth.forbidden');
    expect(await code(s.port.openPatientSession(s.preAuth('B'), OPEN))).toBe('common.not_found'); expect(s.inserted).toHaveLength(0);
  });
  it('two opens give two different tokens (fresh 256-bit token each time)', async () => {
    const s = setup(); const a = await s.port.openPatientSession(s.preAuth(), OPEN); const b = await s.port.openPatientSession(s.preAuth(), OPEN);
    expect(a.sessionToken).not.toBe(b.sessionToken); expect(s.inserted).toHaveLength(2);
  });
});

describe('provisionPatientMembership (patient pre_auth context only; idempotent per accountId; no phone / e-mail anywhere)', () => {
  it('-> { membershipId, userId } from createPatientMembership(ctx, { accountId }) with exactly that one key; a repeat for the same account returns the SAME ids', async () => {
    const s = setup(); const a = await s.port.provisionPatientMembership(s.preAuth(), { accountId: ACCOUNT as any }); const b = await s.port.provisionPatientMembership(s.preAuth(), { accountId: ACCOUNT as any });
    expect(a).toEqual({ membershipId: mid(20), userId: mid(20 + 0x1000) }); expect(b).toEqual(a);
    expect(s.created).toEqual([{ accountId: ACCOUNT }, { accountId: ACCOUNT }]);
  });
  it('non-uuid accountId -> common.validation_failed with no repo call; staff / partner / system / non-pre_auth callers -> auth.forbidden', async () => {
    const s = setup(); expect(await code(s.port.provisionPatientMembership(s.preAuth(), { accountId: 'x' as any }))).toBe('common.validation_failed');
    const post = makeCtx('A', 'patient', 'post'); s.st.claims.set(post.actor.id, { aal: 'aal1', membership_id: mid(20), session_state: 'active' });
    for (const ctx of [makeCtx('A', 'user', 'admin'), makeCtx('A', 'partner', 'p'), makeCtx('A', 'system', 'default'), post]) expect(await code(s.port.provisionPatientMembership(ctx, { accountId: ACCOUNT as any }))).toBe('auth.forbidden');
    expect(s.created).toHaveLength(0);
  });
});

describe('revokePatientSessions({ deactivateMembership: true }) (A28.2; the patient actor never writes identity tables directly)', () => {
  const sys = () => makeCtx('A', 'system', 'default');
  it('system caller: revokes the sessions THEN deactivates the patient membership once; returns { revokedSessions }', async () => {
    const s = setup(); const r = await s.port.revokePatientSessions(sys(), { membershipId: mid(20) as any, reason: 'deactivate', deactivateMembership: true });
    expect(r).toEqual({ revokedSessions: 1 }); expect(s.deactivated).toEqual([{ membershipId: mid(20) }]); expect(s.order).toEqual(['revoke', 'deactivate']); expect(s.st.revoked).toEqual([{ membershipId: mid(20), reason: 'deactivate' }]);
  });
  it('deactivateMembership=false never deactivates; the patient may revoke + deactivate only their OWN membership', async () => {
    const s = setup(); await s.port.revokePatientSessions(sys(), { membershipId: mid(20) as any, reason: 'logout', deactivateMembership: false }); expect(s.deactivated).toHaveLength(0);
    const own = makeCtx('A', 'patient', 'pt'); s.st.claims.set(own.actor.id, { aal: 'aal1', membership_id: mid(20), session_state: 'active' });
    await expect(s.port.revokePatientSessions(own, { membershipId: mid(20) as any, reason: 'deactivate', deactivateMembership: true })).resolves.toEqual({ revokedSessions: 1 });
    expect(await code(s.port.revokePatientSessions(own, { membershipId: mid(21) as any, reason: 'deactivate', deactivateMembership: true }))).toBe('auth.forbidden');
    expect(s.deactivated).toEqual([{ membershipId: mid(20) }]);
  });
  it('a non-patient / other-tenant membership -> common.not_found and NOTHING deactivated or revoked; a bad reason -> common.validation_failed first', async () => {
    const s = setup();
    for (const id of [mid(2), mid(30), mid(99)]) expect(await code(s.port.revokePatientSessions(sys(), { membershipId: id as any, reason: 'deactivate', deactivateMembership: true })), id).toBe('common.not_found');
    expect(await code(s.port.revokePatientSessions(sys(), { membershipId: mid(20) as any, reason: 'because', deactivateMembership: true }))).toBe('common.validation_failed');
    expect(s.deactivated).toHaveLength(0); expect(s.st.revoked).toHaveLength(0);
  });
});

