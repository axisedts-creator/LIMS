export interface FakeSeed { materials?: Row[]; levels?: Row[]; lots?: Row[]; maps?: Row[]; instruments?: Row[] }

const pgErr = (code: string, constraint: string) => Object.assign(new Error('pg error'), { code, constraint });

/** In-memory repo, tenant-aware like RLS + the explicit predicate; emulates the DDL unique indexes and the composite FKs of 05-SCHEMA §2. */
export function makeRepo(seed: FakeSeed = baseSeed()) {
  const materials = (seed.materials ?? []).map((r) => ({ ...r }));
  const levels = (seed.levels ?? []).map((r) => ({ ...r }));
  const lots = (seed.lots ?? []).map((r) => ({ ...r }));
  const maps = (seed.maps ?? []).map((r) => ({ ...r }));
  const instruments = seed.instruments ?? [];
  const calls: Array<{ op: string; tenantId?: string; args: unknown[] }> = [];
  const rec = <T>(op: string, tenantId: string | undefined, args: unknown[], fn: () => T): T => { calls.push({ op, tenantId, args }); return fn(); };
  const mine = (xs: Row[], t: string) => xs.filter((x) => x['tenant_id'] === t);
  const out = <T extends Row | undefined>(r: T): T => (r ? structuredClone(r) : r);
  const clones = (xs: Row[]) => structuredClone(xs);
  const bump = (r: Row, patch: Row) => { Object.assign(r, patch, { version: r['version'] + 1, updated_at: NOW }); return structuredClone(r); };
  const stamp = (t: string, row: Row, extra: Row = {}): Row => ({ is_active: true, version: 1, created_at: NOW, updated_at: NOW, ...row, ...extra, tenant_id: t });
  const upd = (xs: Row[]) => (t: string, id: string, v: number, patch: Row) => { const r = mine(xs, t).find((x) => x['id'] === id); return !r || r['version'] !== v ? undefined : bump(r, patch); };
  const filt = (xs: Row[], q: Row, keys: Record<string, string>) => xs.filter((r) => Object.entries(keys).every(([qk, col]) => q[qk] === undefined || r[col] === q[qk]));
  const repo: SetupRepo = {
    async listMaterials(_tx, t, q) {
      return rec('listMaterials', t, [q], () => {
        let rows = mine(materials, t).filter((m) => m['is_active'] === q.isActive);
        if (q.q) rows = rows.filter((m) => m['code'].startsWith(q.q) || m['name'].startsWith(q.q));
        rows = [...rows].sort((a, b) => (q.sort === 'code' ? a['code'].localeCompare(b['code']) : b['created_at'].localeCompare(a['created_at'])));
        return { rows: clones(rows) };
      });
    },
    async insertMaterial(_tx, t, row) {
      return rec('insertMaterial', t, [row], () => {
        if (mine(materials, t).some((m) => m['code'] === row['code'])) throw pgErr('23505', 'control_materials__tenant_code__uq');
        const r = stamp(t, row); materials.push(r); return structuredClone(r);
      });
    },
    async findMaterial(_tx, t, id) { return rec('findMaterial', t, [id], () => out(mine(materials, t).find((m) => m['id'] === id))); },
    async updateMaterial(_tx, t, id, v, patch) { return rec('updateMaterial', t, [id, v, patch], () => upd(materials)(t, id, v, patch)); },
    async listLevels(_tx, t, ids) { return rec('listLevels', t, [ids], () => clones(mine(levels, t).filter((l) => ids.includes(l['material_id'])))); },
    async insertLevel(_tx, t, row) {
      return rec('insertLevel', t, [row], () => {
        if (mine(levels, t).some((l) => l['material_id'] === row['material_id'] && l['level_code'] === row['level_code'])) throw pgErr('23505', 'control_levels__tenant_material_code__uq');
        const r = stamp(t, row); levels.push(r); return structuredClone(r);
      });
    },
    async findLevel(_tx, t, id) { return rec('findLevel', t, [id], () => out(mine(levels, t).find((l) => l['id'] === id))); },
    async updateLevel(_tx, t, id, v, patch) { return rec('updateLevel', t, [id, v, patch], () => upd(levels)(t, id, v, patch)); },
    async listLotsByMaterials(_tx, t, ids) { return rec('listLotsByMaterials', t, [ids], () => clones(mine(lots, t).filter((l) => ids.includes(l['material_id'])))); },
    async listLots(_tx, t, q) {
      return rec('listLots', t, [q], () => {
        let rows = filt(mine(lots, t), q, { materialId: 'material_id', levelId: 'level_id', isActive: 'is_active' });
        if (q.expiresOnTo) rows = rows.filter((l) => l['expires_on'] < q.expiresOnTo!);
        rows = [...rows].sort((a, b) => (q.sort === 'expires_on' ? a['expires_on'].localeCompare(b['expires_on']) : b['created_at'].localeCompare(a['created_at'])));
        return { rows: clones(rows) };
      });
    },
    async insertLot(_tx, t, row) {
      return rec('insertLot', t, [row], () => {
        if (mine(lots, t).some((l) => l['level_id'] === row['level_id'] && l['lot_no'] === row['lot_no'])) throw pgErr('23505', 'control_lots__tenant_level_lot__uq');
        const r = stamp(t, row); lots.push(r); return structuredClone(r);
      });
    },
    async findLot(_tx, t, id) { return rec('findLot', t, [id], () => out(mine(lots, t).find((l) => l['id'] === id))); },
    async updateLot(_tx, t, id, v, patch) { return rec('updateLot', t, [id, v, patch], () => upd(lots)(t, id, v, patch)); },
    async listMaps(_tx, t, q) { return rec('listMaps', t, [q], () => ({ rows: clones(filt(mine(maps, t), q, { instrumentId: 'instrument_id', lotId: 'lot_id', isActive: 'is_active' })) })); },
    async insertMap(_tx, t, row) {
      return rec('insertMap', t, [row], () => {
        if (!mine(instruments, t).some((i) => i['id'] === row['instrument_id'])) throw pgErr('23503', 'control_id_maps__instrument__fk');
        if (!mine(lots, t).some((l) => l['id'] === row['lot_id'])) throw pgErr('23503', 'control_id_maps__lot__fk');
        if (mine(maps, t).some((m) => m['is_active'] && m['instrument_id'] === row['instrument_id'] && m['control_id_raw'] === row['control_id_raw'] && (m['control_lot_raw'] ?? '') === (row['control_lot_raw'] ?? ''))) {
          throw pgErr('23505', 'control_id_maps__tenant_key__p_uq');
        }
        const r = stamp(t, row); maps.push(r); return structuredClone(r);
      });
    },
    async findMap(_tx, t, id) { return rec('findMap', t, [id], () => out(mine(maps, t).find((m) => m['id'] === id))); },
    async updateMap(_tx, t, id, v, patch) { return rec('updateMap', t, [id, v, patch], () => upd(maps)(t, id, v, patch)); },
    async listInstrumentLabels(_tx, t, ids) {
      return rec('listInstrumentLabels', t, [ids], () => mine(instruments, t).filter((i) => ids.includes(i['id'])).map((i) => ({ instrument_id: i['id'], instrument_code: i['instrument_code'], display_name: i['display_name'] })));
    },
  };
  return {
    repo, materials, levels, lots, maps, calls,
    callsOf: (op: string) => calls.filter((c) => c.op === op),
    mutations: () => calls.filter((c) => /^(insert|update)/.test(c.op)),
  };
}
export type FakeRepo = ReturnType<typeof makeRepo>;

