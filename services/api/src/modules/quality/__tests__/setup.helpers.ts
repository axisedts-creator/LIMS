/** Real-shaped service ctx. `roles` may throw auth.forbidden for a permission; `tx.query` records every statement (incl. app.enqueue_job). */
export function makeCtx(over: { tenantId?: string; roles?: (c: { permission: string; centreId?: string }) => void; now?: string; enqueueFails?: boolean } = {}) {
  const tenantId = over.tenantId ?? TENANT_A;
  const asserted: Array<{ permission: string; centreId?: string }> = [];
  const queries: Array<{ text: string; values: unknown[] }> = [];
  const tx = {
    async query(text: string, values: unknown[] = []) {
      queries.push({ text, values });
      if (over.enqueueFails && /app\.enqueue_job/i.test(text)) throw new Error('queue unavailable');
      return { rows: [] };
    },
  };
  const actor = { type: 'user', id: USER, membershipId: MEM };
  const ctx: any = {
    tenantId, actor, requestId: REQ_ID, tx, now: () => over.now ?? NOW,
    ports: {
      IdentityPort: {
        assertRole: async (_c: unknown, r: { permission: string; centreId?: string }) => { asserted.push(r); over.roles?.(r); },
        getTenantSettings: async () => ({ timezone: 'Asia/Kathmandu' }),
      },
    },
    audit: { access: async () => undefined },
    log: { info() {}, warn() {}, error() {} },
  };
  const enqueues = () => queries.filter((q) => /app\.enqueue_job/i.test(q.text)).map((q) => ({
    task: q.values[0] as string, payload: JSON.parse(String(q.values[1])) as Row, key: q.values[2] as string,
  }));
  return { ctx, asserted, queries, enqueues };
}
