  listMaps(tx: any, tenantId: string, q: { instrumentId?: string; lotId?: string; isActive?: boolean; cursor?: string; limit: number }): Promise<Page>;
  insertMap(tx: any, tenantId: string, row: Row): Promise<Row>;                            // active duplicate key -> { code: '23505' }; unknown instrument -> { code: '23503', constraint: 'control_id_maps__instrument__fk' }
  findMap(tx: any, tenantId: string, id: string): Promise<Row | undefined>;
  updateMap(tx: any, tenantId: string, id: string, expectedVersion: number, patch: Row): Promise<Row | undefined>;
