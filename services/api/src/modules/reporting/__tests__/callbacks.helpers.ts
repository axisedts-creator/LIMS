// C6-T29 test helpers (not a test file). Synthetic data only. World for CB1 receiveProviderCallback / CB2 verifyProviderCallback (02-TRD §6.7), LD-49 (b), CR-C6-001 raw body.
// NOT backed by the shared portal fake: the handler may only talk to the DB through ONE statement, the DEFINER `SELECT app.reporting_ingest_provider_callback($1, $2, $3::jsonb)`
// (provider_kind text, token sha256 bytea 32 bytes, events jsonb string) on ctx.tx (= the anonymous tx of x-anonymous-tx). Every other statement is journalled in `stmts`.
//
// ASSUMED CONTRACT (repeated in .orchestra/notes/C6-T29-tests.md; the spec leaves these open):
//   - handler request: { params: { callback_token }, query, headers (lower-case keys), body: ignored, rawBody: Buffer } — CR-C6-001 "x-raw-body operations receive req.rawBody".
//   - ctx: { clientIp, tx (anonymous), now, log, requestId, db: { withTenantScope(tx, tenantId, systemActorId, fn) }, queue: { enqueue(tx, identifier, payload, jobKey?) },
//            core: { systemActorOf(module) } } — LD-49: "ctx.queue.enqueue inside withTenantScope(returned tenant, the reporting system actor)".
//   - the DEFINER (LD-49 (b)) returns the resolved tenant id, NULL when the token/provider_kind/payload is rejected (it never enqueues); the handler never reads tables itself.
//   - adapter: non-production => the `recording` transport only (REQ-SEC-136). Its callback wire format is defined HERE (ours, test-only):
//       body = JSON {"events":[{"provider_message_id": string, "status": "sent"|"delivered"|"read"|"failed", "occurred_at"?: ISO}]},
//       header `x-recording-signature` = lower-case hex sha256 of the RAW body bytes. A bad/missing signature or an unparsable/unknown-status body throws => callback_rejected.
//     The handler passes the DEFINER events { id (uuid), provider_message_id, status_raw, mapped_status, occurred_at? } (id generated by the API, 04 D9).
import { createHash } from 'node:crypto';
import { hashToken, issueToken } from '../domain/tokens.js';
import { TENANT_A, TENANT_B, NOW, idN, type Row } from './portal.helpers.js';

export { TENANT_A, TENANT_B, NOW, idN, type Row };
export const SYS_REPORTING = idN(0x5001);
export const SYS_OTHER = idN(0x5002);
export const ACC_A = idN(0xacc1);          // tenant A, recording, active
export const ACC_B = idN(0xacc2);          // tenant B, recording, active
export const ACC_OFF = idN(0xacc3);        // tenant A, recording, inactive
export const ACC_SMS = idN(0xacc4);        // tenant A, sms_sparrow (token is valid but not for the recording adapter)
export const IP = '203.0.113.50';
export const sha256hex = (b: Uint8Array | string) => createHash('sha256').update(b).digest('hex');
export const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const DEF = /\bapp\.reporting_ingest_provider_callback\s*\(/i;

export interface CbEvent { provider_message_id: string; status: string; occurred_at?: string }
/** The recording adapter's raw body. `spaced` produces non-canonical JSON so only the RAW bytes verify the signature. */
export const cbBody = (events: CbEvent[], spaced = false): Buffer =>
  Buffer.from(spaced ? `{ "events" :\n [ ${events.map((e) => JSON.stringify(e)).join(' ,\n ')} ]\n}\n` : JSON.stringify({ events }), 'utf8');
export const sign = (raw: Uint8Array) => sha256hex(raw);

export function makeCallbackWorld() {
  const tok = { a: issueToken('callback'), b: issueToken('callback'), off: issueToken('callback'), sms: issueToken('callback') };
  const accounts: Row[] = [
    { id: ACC_A, tenant_id: TENANT_A, provider_kind: 'recording', is_active: true, callback_token_sha256: Buffer.from(tok.a.tokenSha256) },
    { id: ACC_B, tenant_id: TENANT_B, provider_kind: 'recording', is_active: true, callback_token_sha256: Buffer.from(tok.b.tokenSha256) },
    { id: ACC_OFF, tenant_id: TENANT_A, provider_kind: 'recording', is_active: false, callback_token_sha256: Buffer.from(tok.off.tokenSha256) },
    { id: ACC_SMS, tenant_id: TENANT_A, provider_kind: 'sms_sparrow', is_active: true, callback_token_sha256: Buffer.from(tok.sms.tokenSha256) },
  ];
  const providerEvents: Row[] = [];
  const stmts: Array<{ text: string; values: unknown[] }> = [];
  const definerCalls: Array<{ kind: unknown; hash: unknown; events: any }> = [];
  const jobs: Array<{ identifier: string; payload: any; jobKey?: string; scope?: { tenantId: string; actorId: string } }> = [];
  const scopeCalls: Array<{ tenantId: string; actorId: string; hadTx: boolean }> = [];
  const enqueueAttempts: unknown[][] = [];
  const logs: string[] = [];
  let scope: { tenantId: string; actorId: string } | undefined;
  let undo: Array<() => void> = [];
  let seq = 0;

  function definer(values: unknown[]): string | null {
    const [kind, hash, eventsArg] = values;
    let events: any; try { events = typeof eventsArg === 'string' ? JSON.parse(eventsArg) : eventsArg; } catch { events = undefined; }
    definerCalls.push({ kind, hash, events });
    const h = hash instanceof Uint8Array ? Buffer.from(hash) : undefined;
    if (!h || h.length !== 32 || !Array.isArray(events) || events.length > 100) return null;
    const acc = accounts.find((a) => (a['callback_token_sha256'] as Buffer).equals(h) && a['is_active'] && a['provider_kind'] === kind);
    if (!acc) return null;
    for (const e of events) {
      const row = { id: e.id, tenant_id: acc['tenant_id'], channel_account_id: acc['id'], provider_kind: kind, provider_message_id: String(e.provider_message_id).slice(0, 128),
        status_raw: String(e.status_raw).slice(0, 64), mapped_status: e.mapped_status, occurred_at: e.occurred_at ?? null, applied_at: null, delivery_id: null, ignored_reason: null };
      if (!['sent', 'delivered', 'read', 'failed'].includes(row.mapped_status)) throw Object.assign(new Error('provider_events__mapped__ck'), { code: '23514' });
      if (typeof e.id !== 'string' || !UUID_RE.test(e.id)) throw Object.assign(new Error('invalid uuid'), { code: '22P02' });
      if (providerEvents.some((p) => p['tenant_id'] === row.tenant_id && p['channel_account_id'] === row.channel_account_id && p['provider_message_id'] === row.provider_message_id && p['mapped_status'] === row.mapped_status)) continue;
      providerEvents.push(row); undo.push(() => { providerEvents.splice(providerEvents.indexOf(row), 1); });
    }
    return acc['tenant_id'] as string;
  }
  const tx: any = {
    async query(text: string, values: unknown[] = []) {
      stmts.push({ text, values: [...values] });
      if (DEF.test(text)) { const t = definer(values); return { rows: [{ reporting_ingest_provider_callback: t, tenant_id: t }] }; }
      return { rows: [] };
    },
    savepoint: async <T>(fn: (t: unknown) => Promise<T>): Promise<T> => fn(tx),
  };

  /** app.enqueue_job semantics (C0 05-SCHEMA §10): the task is per_tenant, payload.tenant_id must equal the caller's tenant claim; same job key collapses. */
  const queue = {
    async enqueue(...args: unknown[]) {
      enqueueAttempts.push(args);
      const identifier = args.find((a): a is string => typeof a === 'string' && /^[a-z_]+\.[a-z_]+/.test(a))!;
      const payload = args.find((a) => a && typeof a === 'object' && !(a as any).query && 'tenant_id' in (a as object)) as any;
      const strings = args.filter((a): a is string => typeof a === 'string' && a !== identifier);
      const jobKey = strings[0] ?? (args.find((a) => a && typeof a === 'object' && 'jobKey' in (a as object)) as any)?.jobKey;
      if (!scope || !payload || payload.tenant_id !== scope.tenantId) throw Object.assign(new Error('job_tenant_mismatch'), { code: 'P0001' });
      if (jobKey !== undefined && jobs.some((j) => j.identifier === identifier && j.jobKey === jobKey)) return;
      jobs.push({ identifier, payload, ...(jobKey === undefined ? {} : { jobKey }), scope: { ...scope } });
    },
  };
  const db = {
    async withTenantScope<T>(...args: unknown[]): Promise<T> {
      const fn = args[args.length - 1] as () => Promise<T>;
      const [t, tenantId, actorId] = args as [unknown, string, string];
      scopeCalls.push({ tenantId, actorId, hadTx: t === tx });
      if (scope) throw new Error('nested withTenantScope');
      scope = { tenantId, actorId };
      try { return await fn(); } finally { scope = undefined; }
    },
  };
  const log = { info: (o: object, m?: string) => logs.push(JSON.stringify({ o, m })), warn: (o: object, m?: string) => logs.push(JSON.stringify({ o, m })), error: (o: object, m?: string) => logs.push(JSON.stringify({ o, m })) };
  const ctx = (over: Row = {}): any => ({ tenantId: undefined, actor: undefined, requestId: idN(0xe1), clientIp: IP, operationId: 'x', tx, now: () => NOW, log, db, queue,
    core: { systemActorOf: (m: string) => (m === 'reporting' ? SYS_REPORTING : SYS_OTHER) }, ...over });

  async function call(op: 'receiveProviderCallback' | 'verifyProviderCallback', req: Row, c: any = ctx()) {
    const handler = ((await import('../index.js')).manifest.handlers as Record<string, any>)[op];
    if (typeof handler !== 'function') throw new Error(`no handler ${op}`);
    undo = [];
    try { return await handler({ params: {}, query: {}, headers: {}, body: undefined, ...req }, c); }
    catch (e) { for (const f of [...undo].reverse()) f(); jobs.length = 0; jobs.push(...committedJobs); throw e; }   // a rejected request leaves no writes (tx rolled back) -- jobs enqueued earlier stay
    finally { committedJobs = [...jobs]; }
  }
  let committedJobs: typeof jobs = [];
  const cb1 = (token: string, raw: Buffer, headers: Row = { 'x-recording-signature': sign(raw) }, c?: any) =>
    call('receiveProviderCallback', { params: { callback_token: token }, headers, rawBody: raw }, c);
  const cb2 = (token: string, query: Row = {}, c?: any) => call('verifyProviderCallback', { params: { callback_token: token }, query, headers: {} }, c);
  return { tok, accounts, providerEvents, stmts, definerCalls, jobs, scopeCalls, enqueueAttempts, logs, ctx, call, cb1, cb2, tx,
    allText: () => JSON.stringify([stmts, logs, jobs]), hash: (t: string) => Buffer.from(hashToken(t)), seqId: () => idN(0x9000 + ++seq) };
}
export type CallbackWorld = ReturnType<typeof makeCallbackWorld>;

/** Everything observable about a failure, minus the stack: byte-identical comparisons. */
export function failureBytes(e: any): string {
  if (!e || typeof e !== 'object') return String(e);
  const o: Record<string, unknown> = { ctor: e.constructor?.name };
  for (const k of Object.getOwnPropertyNames(e).sort()) if (k !== 'stack') o[k] = e[k];
  return JSON.stringify(o);
}
export async function failure(p: Promise<unknown>): Promise<any> { try { await p; } catch (e) { return e; } throw new Error('expected rejection, got success'); }
