// C6-T06 domain/document.ts: ReportDocument builder (02-TRD §4.3/§4.4/§4.5; PRD AC-02.7, AC-03.1 (data), AC-03.6, AC-03.7 (data); 07-SECURITY T15, snapshot P3). Pure.
// Assumed API (spec gives types, not signatures): buildReportDocument(input: BuildDocumentInput): ReportDocument — see document.fixtures.ts header for the input shape.
//   Port-shaped inputs (LabPort OrderResults, CatalogPort TestDefinition/PanelDefinition/ReferrerProfile, FrontdeskPort OrderSummary/PatientDemographics,
//   IdentityPort Signatory/TenantSettings) + {includeOrderItemIds, centre, config, commentTexts, qrVerifyUrl, reportedAt, complete, earlierReleased, regeneration?}.
//   reportKind comes from versionKind() (version.ts) over the included results; statusLabel is its display form.
// Golden JSON (./golden/*.json) is hand-written from the spec, not generated by the implementation. Goldens drop `comment` (asserted separately)
//   and the optional "Specimen: " prefix on specimenLine (TRD only says the value is the label; the prefix may be added by the template).
// Assumptions flagged: department order = first appearance in order-item order; signatories (approvers mode) ordered by first approval time, capped by config.maxSignatories.
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { buildReportDocument } from '../document.js';
import { I, SIGNATORIES, deepFreeze, id, makeInput, withItems } from './document.fixtures.js';

const golden = (n: string) => JSON.parse(readFileSync(new URL(`./golden/${n}.json`, import.meta.url), 'utf8'));
const norm = (sections: any[]) => JSON.parse(JSON.stringify(sections, (k, v) => (k === 'comment' ? undefined : k === 'specimenLine' && typeof v === 'string' ? v.replace(/^Specimen:\s*/, '') : v)));
const lines = (doc: any): any[] => doc.sections.flatMap((s: any) => (s.kind === 'department' ? s.blocks.flatMap((b: any) => b.subgroups.flatMap((g: any) => g.lines)) : []));
const lineOf = (doc: any, name: string) => lines(doc).find((l) => l.name === name);

const amendedInput = (over: Record<string, unknown> = {}) => {
  const inp = makeInput({ includeOrderItemIds: [I.itemPkg], earlierReleased: true, ...over });
  const hgb = inp.orderResults.items[1].results[0];
  hgb.versionNo = 2;
  hgb.amendment = { previousVersionNo: 1, reasonCode: 'corrected_value', reasonText: 'Synthetic correction', amendedAt: '2026-11-05T09:00:00.000Z' };
  return inp;
};

describe('golden snapshots (sections, kind, status label, amendment notes)', () => {
  const cases: [string, () => any][] = [
    ['cbc', () => withItems(I.itemPkg)],
    ['lipid', () => withItems(I.itemLipid)],
    ['urine', () => withItems(I.itemUrine)],
    ['formula', () => withItems(I.itemRatio)],
    ['amended', () => amendedInput()],
  ];
  for (const [name, input] of cases) {
    it(`${name}`, () => {
      const g = golden(name); const doc: any = buildReportDocument(input());
      expect(doc.reportKind).toBe(g.reportKind);
      expect(doc.statusLabel).toBe(g.statusLabel);
      expect(norm(doc.sections)).toEqual(g.sections);
      expect(doc.amendmentNotes).toEqual(g.amendmentNotes);
    });
  }
  it('partial: only the included ready items print; kind partial / "Partial" (complete = false)', () => {
    const doc: any = buildReportDocument(makeInput({ includeOrderItemIds: [I.itemLipid, I.itemUrine], complete: false }));
    expect(doc.reportKind).toBe('partial'); expect(doc.statusLabel).toBe('Partial');
    expect(norm(doc.sections)).toEqual([...golden('lipid').sections, ...golden('urine').sections]);
    expect(JSON.stringify(doc)).not.toMatch(/Haemoglobin|Glucose|BUN\/Creatinine/); // pending items' results never leak into a partial snapshot
  });
  it('envelope: schemaVersion 1, family laboratory, empty attachment arrays, calendar/timezone passthrough', () => {
    const doc: any = buildReportDocument(withItems(I.itemPkg));
    expect(doc.schemaVersion).toBe(1); expect(doc.family).toBe('laboratory');
    expect(doc.outsourcedAttachments).toEqual([]); expect(doc.instrumentPdfAttachments).toEqual([]);
    expect(doc.calendarDisplay).toBe('AD'); expect(doc.timezone).toBe('Asia/Kathmandu');
    expect(doc.qr).toEqual({ verifyUrl: 'https://portal.example.invalid/v/AAAAAAAAAAAAAAAAAAAAAA' });
  });
});

