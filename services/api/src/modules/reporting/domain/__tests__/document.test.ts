describe('value formatting (TRD §4.4): catalog decimals, no float conversion, never computed', () => {
  it('pads to the analyte decimals (92 -> 92.0, 5.1 -> 5.10, 7400 -> 7400)', () => {
    const d: any = buildReportDocument(withItems(I.itemPkg));
    expect(lineOf(d, 'Glucose').valueText).toBe('92.0'); expect(lineOf(d, 'RBC Count').valueText).toBe('5.10'); expect(lineOf(d, 'WBC Count').valueText).toBe('7400');
  });
  it('DecimalString beyond float precision survives exactly', () => {
    const inp = withItems(I.itemPkg); inp.orderResults.items[0].results[0].valueNumeric = '123456789012345678.9';
    expect(lineOf(buildReportDocument(inp), 'Glucose').valueText).toBe('123456789012345678.9');
    inp.tests = inp.tests.map((t: any) => (t.id === I.tGlu ? { ...t, analytes: [{ ...t.analytes[0], decimals: 3 }] } : t));
    expect(lineOf(buildReportDocument(inp), 'Glucose').valueText).toBe('123456789012345678.900');
  });
  it('ordinal value prints the set display of the ordinal code (2P -> "2+", NEG -> "Negative"), sub-heading kept', () => {
    const d: any = buildReportDocument(withItems(I.itemUrine));
    expect(lineOf(d, 'Protein').valueText).toBe('2+'); expect(lineOf(d, 'Sugar').valueText).toBe('Negative');
    expect(d.sections[0].blocks[0].subgroups[0].subheading).toBe('Chemical examination');
  });
  it('formula analyte prints the stored (C5-calculated) value; inputs absent -> still printed, not recomputed', () => {
    expect(lineOf(buildReportDocument(withItems(I.itemRatio)), 'BUN/Creatinine ratio').valueText).toBe('12.5');
  });
  it('refRangeText: snapshot text beats low/high; low+high "a – b"; only high "< h"; only low "> l"; none -> absent', () => {
    const d: any = buildReportDocument(makeInput());
    expect(lineOf(d, 'WBC Count').refRangeText).toBe('4000 - 11000'); expect(lineOf(d, 'Haemoglobin').refRangeText).toBe('13.0 – 17.0');
    expect(lineOf(d, 'Total Cholesterol').refRangeText).toBe('< 200'); expect(lineOf(d, 'HDL Cholesterol').refRangeText).toBe('> 40');
    expect(lineOf(d, 'pH').refRangeText).toBeUndefined();
  });
  it('name = printName ?? name; unitText from the result unit', () => {
    const d: any = buildReportDocument(withItems(I.itemPkg));
    expect(lineOf(d, 'Haemoglobin').unitText).toBe('g/dL'); expect(lineOf(d, 'Haemoglobin').analyteId).toBe(I.aHgb);
    expect(lineOf(d, 'HGB')).toBeUndefined();
  });
  it('a different printName is used when set; falls back to name when absent', () => {
    const inp = withItems(I.itemPkg);
    inp.tests = inp.tests.map((t: any) => (t.id === I.tGlu ? { ...t, analytes: [{ ...t.analytes[0], printName: 'Blood Sugar (F)' }] } : t));
    expect(lineOf(buildReportDocument(inp), 'Blood Sugar (F)')).toBeDefined();
  });
});

