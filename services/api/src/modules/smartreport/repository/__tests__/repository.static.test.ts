// C14 T02 — static structure of services/api/src/modules/smartreport/repository/*.repo.ts (no database needed).
// 02-TRD §3 file tree (repository/: library blocks rules mappings groups denyTerms summaries bindings reviews llmRuns codedSets) + 06 row T02 ("Repositories for all tables with explicit tenant_id
// filters and optimistic version updates") + 05-SCHEMA §1 (table list, parsed at test time) + §6 (no DELETE grant on any smartreport table) + 07-SECURITY REQ-SEC-022/023/024.
// Behaviour (tenant filter, versions, EXPLAIN on 05-SCHEMA §5) is in repository.integration.test.ts.
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

const here = fileURLToPath(new URL('..', import.meta.url));                      // .../smartreport/repository/
const root = fileURLToPath(new URL('../../../../../../../', import.meta.url));
const REQUIRED_FILES = ['library.repo.ts', 'blocks.repo.ts', 'rules.repo.ts', 'mappings.repo.ts', 'groups.repo.ts', 'denyTerms.repo.ts',
  'summaries.repo.ts', 'bindings.repo.ts', 'reviews.repo.ts', 'llmRuns.repo.ts', 'codedSets.repo.ts'];

const repoFiles = (): string[] => (existsSync(here) ? readdirSync(here).filter((f) => f.endsWith('.repo.ts')) : []);
const source = (f: string) => readFileSync(join(here, f), 'utf8');
const code = (s: string) => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ');

function specTables(): string[] {
  const md = readFileSync(join(root, 'spec', 'chunks', 'C14-smart-report', '05-SCHEMA.md'), 'utf8').replace(/\r\n?/g, '\n');
  const sec = md.slice(md.indexOf('## 1. Table inventory'), md.indexOf('## 2. Tenant tables'));
  const names = sec.split('\n').filter((l) => l.startsWith('| `smartreport.')).flatMap((l) => (l.split('|')[1] ?? '').match(/smartreport\.[a-z_]+/g) ?? []);
  return [...new Set(names)].filter((n) => n !== 'smartreport.event_inbox');      // generated by C0 only (05-SCHEMA §1, C0 05-SCHEMA §3.9)
}

describe('T02 repository files', () => {
  it('the spec lists 14 smartreport tables (3 global coded sets + 11 tenant tables); event_inbox is C0-generated', () => {
    expect(specTables().length).toBe(14);
  });

  it.each(REQUIRED_FILES)('%s exists under repository/', (f) => {
    expect(repoFiles()).toContain(f);
  });

  it('every table of 05-SCHEMA §1 is read or written by some *.repo.ts', () => {
    const all = repoFiles().map((f) => code(source(f))).join('\n');
    const missing = specTables().filter((t) => !new RegExp(`\\b${t.replace('.', '\\.')}\\b`).test(all));
    expect(missing).toEqual([]);
  });

  it('SQL touches schema smartreport only (no FROM/JOIN/INTO/UPDATE on another schema — other chunks are reached through ports, 02-TRD §3)', () => {
    for (const f of repoFiles()) {
      const bad = [...code(source(f)).matchAll(/\b(?:from|join|into|update)\s+(?!smartreport\.)([a-z_]+\.[a-z_]+)\b/gi)].map((m) => m[1]!);
      expect(bad, f).toEqual([]);
    }
  });

  it('no repository deletes rows (no DELETE grant on any smartreport table; removal = is_active = false, 05-SCHEMA §4/§6, 08 A17 P-18(a))', () => {
    for (const f of repoFiles()) expect(code(source(f)), f).not.toMatch(/\bdelete\s+from\b|\btruncate\b|\bdrop\s+table\b/i);
  });

  it('every tenant-table repository names tenant_id (explicit filter, REQ-SEC-024); only codedSets.repo.ts (global g_cs_*) may omit it', () => {
    for (const f of repoFiles().filter((x) => x !== 'codedSets.repo.ts')) expect(code(source(f)), f).toMatch(/\btenant_id\b/);
    if (repoFiles().includes('codedSets.repo.ts')) {
      const s = code(source('codedSets.repo.ts'));
      expect(s).toMatch(/smartreport\.g_cs_organ_groups/);
      expect(s).toMatch(/smartreport\.g_cs_summary_reject_reasons/);
    }
  });

  it('the updatable tables use the optimistic version predicate (version = $n) and bump version', () => {
    for (const f of ['library.repo.ts', 'blocks.repo.ts', 'rules.repo.ts', 'mappings.repo.ts', 'groups.repo.ts', 'denyTerms.repo.ts', 'summaries.repo.ts']) {
      const s = code(source(f));
      expect(s, f).toMatch(/version\s*=\s*version\s*\+\s*1/i);
      expect(s, f).toMatch(/\bversion\s*=\s*\$\d+/i);
    }
  });

  it('class A tables (bindings, reviews, llm runs) are append-only: no UPDATE statement (no UPDATE grant, 05-SCHEMA §6)', () => {
    for (const f of ['bindings.repo.ts', 'reviews.repo.ts', 'llmRuns.repo.ts']) expect(code(source(f)), f).not.toMatch(/\bupdate\s+smartreport\./i);
  });

  it('no SQL string is built by interpolating a value (template literal `${...}` inside a statement is allowed only for column-name allow-lists)', () => {
    for (const f of repoFiles()) {
      const s = code(source(f));
      expect(s, f).not.toMatch(/(?:WHERE|AND|VALUES|=)\s*['"]?\$\{\s*(?:row|patch|args?|input|opts?|id|tenantId|rc\.tenantId)\b/);
      expect(s, f).not.toMatch(/\bsql\.raw\b|\beval\s*\(/);
    }
  });
});
