// T0B-SWEEP-2 (LD-270 done_when 2, 3, 5): depth counts, results markdown with a DEPTH column, BUG list by root-cause guess as the LAST section.
import type { DefectClass, Depth, Verdict } from './classify.js';

export interface SweepRow {
  module: string; operationId: string; method: string; path: string; sessionKind: string; auth: string; holdsPermission: boolean;
  status: number; errorCode: string; verdict: Verdict; depth: Depth; reason: string; rootCause: string; defectClass: DefectClass | ''; detail: string;
}
const DEPTHS: Depth[] = ['DEEP', 'SHALLOW', 'NOT EXERCISED'];
const zero = (): Record<Depth, number> => ({ DEEP: 0, SHALLOW: 0, 'NOT EXERCISED': 0 });

export function summarize(rows: SweepRow[]): { total: number; byDepth: Record<Depth, number>; byModule: Record<string, Record<Depth, number>> } {
  const byDepth = zero();
  const byModule: Record<string, Record<Depth, number>> = {};
  for (const r of rows) { byDepth[r.depth]++; (byModule[r.module] ??= zero())[r.depth]++; }
  return { total: rows.length, byDepth, byModule };
}

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\s+/g, ' ').slice(0, 220);
const counts = (c: Record<Depth, number>) => DEPTHS.map((d) => `${d}: ${c[d]}`).join(' · ');

/** `sections` (e.g. the stack-level explanation) go before the BUG list, which stays last. */
export function renderResults(rows: SweepRow[], meta: { at: string; title?: string; sections?: string[] }): string {
  const s = summarize(rows);
  const v = (x: Verdict) => rows.filter((r) => r.verdict === x).length;
  const out: string[] = [`# ${meta.title ?? 'T0B-SWEEP-2 results'} (generated by \`pnpm --filter @lims/api sweep\`; do not edit)`, '',
    `Run: ${meta.at}. Operations: ${s.total}. WIRED: ${v('WIRED')}. DEFECT: ${v('DEFECT')}. NOT_EXERCISED: ${v('NOT_EXERCISED')}.`, '',
    `Depth (LD-270): ${counts(s.byDepth)}.`,
    'DEEP = reached the service (2xx, a domain 4xx, any 5xx); SHALLOW = 400 common.validation_failed (input validation); NOT EXERCISED = 429, timeout, harness error.',
    'A 429 is never WIRED. Defect class: BUG (code wrong or unwired), CONFIG (provider / flag / secret absent in a test environment), HARNESS (test setup).', '',
    '## Depth per module', '', '| module | DEEP | SHALLOW | NOT EXERCISED |', '|---|---|---|---|',
    ...Object.entries(s.byModule).map(([m, c]) => `| ${m} | ${c.DEEP} | ${c.SHALLOW} | ${c['NOT EXERCISED']} |`), ''];
  for (const m of [...new Set(rows.map((r) => r.module))]) {
    const rs = rows.filter((r) => r.module === m);
    out.push(`## ${m} (${counts(s.byModule[m]!)}; ${rs.filter((r) => r.verdict === 'DEFECT').length} defects / ${rs.length})`, '',
      '| operation | session kind | status | error_code | verdict | depth | class | detail |', '|---|---|---|---|---|---|---|---|');
    for (const r of rs) {
      const why = r.verdict === 'DEFECT' || r.depth === 'SHALLOW' ? r.detail || r.reason : r.reason;
      out.push(`| ${r.operationId} | ${r.sessionKind}${r.auth === 'bearer' ? '' : ` (${r.auth})`} | ${r.status} | ${r.errorCode || '-'} | ${r.verdict} | ${r.depth} | ${r.defectClass || '-'} | ${cell(why)} |`);
    }
    out.push('');
  }
  const defects = rows.filter((r) => r.verdict === 'DEFECT');
  out.push('## Defects by class', '', '| class | defects | operations |', '|---|---|---|',
    ...(['BUG', 'CONFIG', 'HARNESS'] as const).map((c) => { const d = defects.filter((r) => r.defectClass === c); return `| ${c} | ${d.length} | ${d.map((r) => r.operationId).join(', ') || '-'} |`; }), '');
  for (const sec of meta.sections ?? []) out.push(sec.trimEnd(), '');
  const bugs = new Map<string, SweepRow[]>();
  for (const r of defects.filter((x) => x.defectClass === 'BUG')) bugs.set(r.rootCause, [...(bugs.get(r.rootCause) ?? []), r]);
  out.push('## BUG list by root-cause guess', '');
  if (!bugs.size) out.push('No BUG defect in this run.');
  for (const [cause, rs] of [...bugs.entries()].sort((a, b) => b[1].length - a[1].length)) {
    out.push(`- **${cell(cause)}** (${rs.length}): ${rs.map((r) => `${r.operationId} (${r.status} ${r.errorCode || '-'})`).join(', ')}`);
  }
  return out.join('\n') + '\n';
}
