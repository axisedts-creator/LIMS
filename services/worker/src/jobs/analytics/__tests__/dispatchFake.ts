import { vi } from 'vitest';
import { createFakeNotificationPort } from '../../../../../../packages/fakes/src/NotificationPort.fake';
import { TENANTS, idFor } from '../../../../../../packages/fakes/src/base';
import { schedulesDb, schedulesRepoMock } from '../../../../../api/src/modules/analytics/service/__tests__/schedulesFake.js';

export { schedulesDb, schedulesRepoMock };
export const TA = TENANTS.A;
export const TB = TENANTS.B;
export const NOW = '2026-11-06T06:00:00.000Z';
export const SYS = '01900000-0000-7000-8000-00000000ff01';
export const ORIGIN = 'https://staff.lims.invalid';
export const mid = (n: number): string => idFor(1, 0xe00 + n);
export const SID = idFor(1, 0x1900);
export const M1 = mid(1), M2 = mid(2), M3 = mid(3), M4 = mid(4), OWNER = mid(9);
export const DASH = 'analytics.dashboard.read', COLL = 'analytics.collections.read', REF = 'analytics.referral_report.read';

export interface Member { membershipId: string; displayName: string; status: string; isActive: boolean; lockedAt?: string; perms: string[]; email: string | null }
export const world = {
  members: new Map<string, Member>(),
  settings: { referralIncentiveReportEnabled: false } as Record<string, unknown>,
  notif: undefined as any, send: undefined as any,
  logs: [] as any[], metrics: [] as { name: string; labels: any }[],
};
export function addMember(id: string, over: Partial<Member> = {}): Member {
  const m: Member = { membershipId: id, displayName: `Test User ${id.slice(-4)}`, status: 'active', isActive: true, perms: [DASH], email: `m${id.slice(-4)}@example.invalid`, ...over };
  world.members.set(id, m);
  return m;
}
export function resetWorld(now = NOW): void {
  process.env.LIMS_ORIGIN_STAFF_WEB = ORIGIN;
  schedulesDb.reset(now);
  world.members.clear(); world.logs.length = 0; world.metrics.length = 0; world.settings = { referralIncentiveReportEnabled: false };
  [M1, M2, M3, M4, OWNER].forEach((m) => addMember(m, m === OWNER ? { perms: [DASH, COLL, REF] } : {}));
  buildNotif();
}
/** (Re)builds the C6 fake from `world.members`; the staff origin = env LIMS_ORIGIN_STAFF_WEB at the time of the call. Call after editing members. */
export function buildNotif(): void {
  const origin = process.env.LIMS_ORIGIN_STAFF_WEB ?? ORIGIN;
  const staffContacts = [...world.members.values()].map((m) => ({
    id: idFor(1, 0x2000 + Number.parseInt(m.membershipId.slice(-3), 16)), tenantId: TA, membershipId: m.membershipId, email: m.email, status: m.isActive ? 'active' as const : 'deactivated' as const,
    actorType: 'user', locked: !!m.lockedAt, permissions: m.perms,
  }));
  world.notif = createFakeNotificationPort({ seed: 1, fixtures: {
    templates: [{ id: idFor(1, 0x803), code: 'analytics.report_ready', purpose: 'scheduled_report_ready', channels: ['email'], params: { lab_name: 'short_text', schedule_name: 'label_text' }, staffOnly: true }],
    staffContacts, staffWebOrigin: origin,
  } as never });
  world.send = vi.spyOn(world.notif, 'sendEmailLink');
}

export function makeJobCtx(o: { tenantId?: string } = {}) {
  const core: any = {
    tenant: async () => ({ id: TA, displayName: 'Test Lab Pvt Ltd', timezone: 'Asia/Kathmandu' }),
    membership: async (_c: unknown, i: { membershipId: string }) => {
      const m = world.members.get(i.membershipId);
      if (!m) throw Object.assign(new Error('not found'), { code: 'common.not_found' });
      return { membershipId: m.membershipId, displayName: m.displayName, status: m.status, isActive: m.isActive, ...(m.lockedAt ? { lockedAt: m.lockedAt } : {}), allCentres: true, centreIds: [], roleCodes: [] };
    },
    membershipPermissions: async (_c: unknown, i: { membershipId: string }) => [...(world.members.get(i.membershipId)?.perms ?? [])],
    memberships: { list: async () => [] },
  };
  const tenantId = o.tenantId ?? TA;
  const ctx: any = {
    tenantId, actor: { type: 'system', id: SYS }, requestId: '01900000-0000-7000-8000-0000000000e1', jobId: '1', attempt: 1, maxAttempts: 5,
    now: () => schedulesDb.clock.now, isNewer: () => true,
    tx: { system: true, tenantId, query: vi.fn(async () => ({ rows: [] })) }, db: { tx: async <T>(fn: (c: any) => Promise<T>) => fn(ctx) },
    core, events: {}, storage: {}, files: {}, audit: { access: vi.fn(async () => undefined) },
    log: { info: (x: unknown) => world.logs.push(x), warn: (x: unknown) => world.logs.push(x), error: (x: unknown) => world.logs.push(x), debug() {} },
    metrics: { inc: (name: string, labels: unknown) => world.metrics.push({ name, labels }), set() {}, observe() {} },
    ports: {
      IdentityPort: { getTenantSettings: async (_c: unknown, i: { keys: readonly string[] }) => Object.fromEntries(i.keys.map((k) => [k, world.settings[k]])) },
      NotificationPort: world.notif,
    },
  };
  return ctx;
}

export async function run(ctx: any, over: { tenant_id?: string } = {}): Promise<void> {
  const { dispatchSchedulesTask } = await import('../tasks/dispatch_schedules.js');
  await dispatchSchedulesTask({ tenant_id: TA, ...over } as never, ctx);
}

