export interface CtxOpts {
  tenantId?: string; attempt?: number; maxAttempts?: number; now?: string;
  /** What ctx.files.scan returns for the bytes it is given (default 'clean'). */
  scan?: (bytes: Uint8Array) => 'clean' | 'infected' | 'unavailable' | Promise<'clean' | 'infected' | 'unavailable'>;
}
export function makeLog() {
  const lines: string[] = [];
  const safe = (v: unknown) => { try { return JSON.stringify(v, (_k, x) => (x instanceof Error ? { name: x.name, message: x.message, stack: x.stack } : typeof x === 'bigint' ? String(x) : x)); } catch { return String(v); } };
  const log: any = {};
  for (const level of ['debug', 'info', 'warn', 'error']) log[level] = (...args: unknown[]) => { lines.push(`${level} ${safe(args)}`); };
  log.child = () => log;
  return { log, lines, text: () => lines.join('\n') };
}

/** Runs `handler(payload, ctx)` the way the worker core does: ctx.tx commits on resolve, rolls back on throw. */
export function makeRunner(db: ValidateDb, handler: (payload: any, ctx: any) => Promise<void>, o: CtxOpts = {}) {
  const tenantId = o.tenantId ?? TENANT_A;
  const scanCalls: Uint8Array[] = [];
  const events: unknown[] = [];
  const l = makeLog();
  const metrics: Array<{ kind: string; name: string; labels: any }> = [];
  const build = (tx: any, attempt: number, maxAttempts: number): any => {
    const ctx: any = {
      tenantId, actor: { type: 'system', id: SYS }, requestId: uid(9000), tx, attempt, maxAttempts, jobId: '1', now: () => o.now ?? NOW, isNewer: () => true,
      events: { publish: async (...a: unknown[]) => { events.push(a); } }, core: {}, storage: {}, audit: {}, log: l.log,
      metrics: { inc: (name: string, labels: any = {}) => { metrics.push({ kind: 'inc', name, labels }); }, set() {}, observe() {} },
      files: { scan: async (bytes: Uint8Array) => { scanCalls.push(bytes); return (o.scan ?? (() => 'clean'))(bytes); } },
    };
    ctx.db = { tx: async (fn: (c: any) => Promise<unknown>) => { const t2 = db.begin(tenantId); try { const r = await fn({ ...ctx, tx: t2 }); t2.commit(); return r; } catch (e) { t2.rollback(); throw e; } } };
    return ctx;
  };
  return {
    scanCalls, events, metrics, log: l,
    /** One attempt. Rejects when the handler throws (after rolling back ctx.tx). */
    async run(payload: any, attempt = o.attempt ?? 1, maxAttempts = o.maxAttempts ?? 3) {
      const tx = db.begin(tenantId);
      try { await handler(payload, build(tx, attempt, maxAttempts)); tx.commit(); } catch (e) { tx.rollback(); throw e; }
    },
  };
}

