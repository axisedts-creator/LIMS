function check(table: string, r: Row): string | undefined {
  if (table === 'imports') {
    if (!IMPORT_STATUS.includes(r.status)) return 'imports__status__ck';
    if (r.summary === null || typeof r.summary !== 'object') return 'imports__summary__nn';
    if (r.error_count != null && !Number.isInteger(r.error_count)) return 'imports__error_count__ck';
  }
  if (table === 'files') {
    if (!['import_upload', 'import_report', 'export'].includes(r.purpose)) return 'files__purpose__ck';
    if (r.content_type !== XLSX_CT) return 'files__ct__ck';
    if (!Number.isInteger(r.byte_size) || r.byte_size < 1 || r.byte_size > 15728640) return 'files__size__ck';
    if (!/^[0-9a-f]{64}$/.test(r.sha256)) return 'files__sha__ck';
    if (typeof r.file_name !== 'string' || r.file_name.length < 1 || r.file_name.length > 200) return 'files__name__ck';
  }
  if (table === 'import_issues') {
    if (!['error', 'warning'].includes(r.severity)) return 'import_issues__sev__ck';
    if (typeof r.sheet !== 'string' || r.sheet.length > 31) return 'import_issues__sheet__ck';
    if (r.column_key != null && String(r.column_key).length > 40) return 'import_issues__col__ck';
    if (!/^[a-z_]+\.[a-z_]+$/.test(r.issue_code)) return 'import_issues__code__ck';
    if (typeof r.message !== 'string' || r.message.length > 300) return 'import_issues__msg__ck';
    if (!Number.isInteger(r.seq)) return 'import_issues__seq__ck';
    if (r.row_no != null && !Number.isInteger(r.row_no)) return 'import_issues__row__ck';
  }
  return undefined;
}

function splitTop(s: string): string[] {
  const out: string[] = []; let depth = 0, q = false, cur = '';
  for (const ch of s) {
    if (ch === "'") q = !q;
    if (!q) { if (ch === '(') depth++; if (ch === ')') depth--; }
    if (ch === ',' && depth === 0 && !q) { out.push(cur.trim()); cur = ''; } else cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}
const coerce = (col: string, v: unknown): unknown => {
  if (v === undefined || v === null) return null;
  if (TS.has(col)) { const d = v instanceof Date ? v : new Date(String(v)); if (Number.isNaN(d.getTime())) throw pgError('22007', `invalid timestamp for ${col}`); return d; }
  if (col === 'summary') return typeof v === 'string' ? JSON.parse(v) : v;
  if (BYTEA.has(col)) { if (!(v instanceof Uint8Array)) throw pgError('42804', `bytea expected for ${col}`); return Buffer.from(v); }
  return v;
};
const key = (v: unknown) => (v instanceof Date ? v.getTime() : v);

export interface Stmt { readonly txId: number; readonly tenantId: string; readonly text: string; readonly values: readonly unknown[] }

export function makeValidateDb() {
  const committed: Record<string, Row[]> = {};
  for (const t of [...WRITABLE, ...READONLY]) committed[t] = [];
  const stmts: Stmt[] = [];
  let nextTx = 1;

  /** Seed committed rows directly (bypasses constraints/RLS: test setup only). */
  const seed = (table: string, ...rows: Row[]) => { committed[table]!.push(...rows.map((r) => ({ ...r }))); };
  const rows = (table: string, tenantId?: string) => committed[table]!.filter((r) => tenantId === undefined || r.tenant_id === tenantId).map((r) => ({ ...r }));

  function begin(tenantId: string) {
    const id = nextTx++;
    const ins: Record<string, Row[]> = {}; for (const t of [...WRITABLE, ...READONLY]) ins[t] = [];
    const patches = new Map<Row, Row>();
    let open = true;
    const visible = (t: string): Row[] => [
      ...committed[t]!.filter((r) => r.tenant_id === tenantId).map((r) => ({ ...r, ...(patches.get(r) ?? {}), __ref: r })),
      ...ins[t]!.map((r) => ({ ...r, __ref: r })),
    ];
    const strip = (r: Row) => { const { __ref, ...rest } = r; return rest; };

    const value = (tok: string, values: readonly unknown[], col?: string): unknown => {
      const t = tok.trim().replace(/::[\w ]+(\[\])?$/, '');
      let m: RegExpExecArray | null;
      if ((m = /^\$(\d+)$/.exec(t))) { if (Number(m[1]) > values.length) throw new Error(`fake: missing bind ${t}`); const v = values[Number(m[1]) - 1]; return col ? coerce(col, v) : v; }
      if (/^now\(\)$/i.test(t)) return new Date(NOW);
      if (/^null$/i.test(t)) return null;
      if (/^true$/i.test(t)) return true;
      if (/^false$/i.test(t)) return false;
      if (/^-?\d+(\.\d+)?$/.test(t)) return Number(t);
      if ((m = /^'((?:[^']|'')*)'$/.exec(t))) { const s = m[1]!.replace(/''/g, "'"); return col ? coerce(col, s) : s; }
      throw new Error(`fake: unsupported SQL value: ${tok}`);
    };
    const colOf = (s: string) => s.trim().replace(/^\w+\./, '');

    const matcher = (where: string | undefined, values: readonly unknown[]): ((r: Row) => boolean) => {
      if (!where?.trim()) return () => true;
      if (/\bOR\b/i.test(where)) throw new Error('fake: unsupported SQL (OR)');
      const conds = where.split(/\s+AND\s+/i).map((c) => c.trim());
      const tests = conds.map((c) => {
        let m: RegExpExecArray | null;
        if ((m = /^([\w.]+)\s+IS\s+NOT\s+NULL$/i.exec(c))) { const k = colOf(m[1]!); return (r: Row) => r[k] != null; }
        if ((m = /^([\w.]+)\s+IS\s+NULL$/i.exec(c))) { const k = colOf(m[1]!); return (r: Row) => r[k] == null; }
        if ((m = /^([\w.]+)\s*=\s*ANY\s*\(\s*(\$\d+)(?:::\w+\[\])?\s*\)$/i.exec(c))) { const k = colOf(m[1]!); const arr = value(m[2]!, values) as unknown[]; return (r: Row) => arr.map(key).includes(key(r[k])); }
        if ((m = /^([\w.]+)\s+(NOT\s+)?IN\s*\((.*)\)$/i.exec(c))) { const k = colOf(m[1]!); const vs = splitTop(m[3]!).map((x) => value(x, values, k)); const neg = !!m[2]; return (r: Row) => vs.map(key).includes(key(r[k])) !== neg; }
        if ((m = /^([\w.]+)\s*(=|<>|!=|>=|<=|>|<)\s*(.+)$/.exec(c))) {
          const k = colOf(m[1]!); const op = m[2]!; const v = key(value(m[3]!, values, k));
          return (r: Row) => { const x = key(r[k]); switch (op) { case '=': return x === v; case '<>': case '!=': return x !== v; case '>': return x! > v!; case '>=': return x! >= v!; case '<': return x! < v!; default: return x! <= v!; } };
        }
        throw new Error(`fake: unsupported SQL condition: ${c}`);
      });
      return (r) => tests.every((t) => t(r));
    };

    const projection = (list: string, rs: Row[]): Row[] => {
      const l = list.trim();
      if (l === '*' || /^\w+\.\*$/.test(l)) return rs.map(strip);
      return rs.map((r) => Object.fromEntries(splitTop(l).map((c) => {
        const m = /^([\w.]+)(?:\s+AS\s+(\w+))?$/i.exec(c.trim()); if (!m) throw new Error(`fake: unsupported SQL column: ${c}`);
        const k = colOf(m[1]!); return [m[2] ?? k, r[k]];
      })));
    };
    /** node-pg wire types: bigint -> string. */
    const wire = (r: Row): Row => { const o = { ...r }; if ('unit_price_paisa' in o && o.unit_price_paisa != null) o.unit_price_paisa = String(o.unit_price_paisa); return o; };

    function checkRow(table: string, r: Row, existing: Row[]) {
      for (const c of REQUIRED[table] ?? []) if (r[c] == null) throw pgError('23502', `null value in column "${c}" of relation "${table}"`);
      const bad = check(table, r); if (bad) throw pgError('23514', `violates check constraint "${bad}"`);
      const pk = PK[table]!;
      if (existing.some((o) => o !== r && pk.every((c) => key(o[c]) === key(r[c])))) throw pgError('23505', `duplicate key value violates unique constraint "${table}__pk"`);
    }

    async function query(text: string, values: readonly unknown[] = []): Promise<{ rows: Row[]; rowCount: number }> {
      if (!open) throw new Error('fake: tx closed');
      stmts.push({ txId: id, tenantId, text, values });
      const sql = text.replace(/\s+/g, ' ').trim().replace(/;$/, '');
      if (!/\bcatalog\.\w+/i.test(sql)) throw new Error(`fake: unsupported SQL: ${sql.slice(0, 80)}`);
      const tm = /\bcatalog\.(\w+)/i.exec(sql)!;
      const table = tm[1]!;
      if (![...WRITABLE, ...READONLY].includes(table)) throw new Error(`fake: unsupported SQL (table catalog.${table}): ${sql.slice(0, 80)}`);
      let m: RegExpExecArray | null;

      if (/^SELECT\b/i.test(sql)) {
        if (/\bJOIN\b/i.test(sql) || /\(\s*SELECT/i.test(sql)) throw new Error('fake: unsupported SQL (join/subquery)');
        m = /^SELECT\s+(.+?)\s+FROM\s+catalog\.\w+(?:\s+(?:AS\s+)?(?!WHERE|ORDER|LIMIT|FOR)\w+)?(?:\s+WHERE\s+(.+?))?(?:\s+ORDER BY\s+(.+?))?(?:\s+LIMIT\s+(\$\d+|\d+))?(?:\s+FOR UPDATE)?$/i.exec(sql);
        if (!m) throw new Error(`fake: unsupported SQL: ${sql.slice(0, 120)}`);
        let rs = visible(table).filter(matcher(m[2], values));
        if (m[3]) {
          const ord = splitTop(m[3]).map((o) => { const p = o.trim().split(/\s+/); return { k: colOf(p[0]!), desc: /^DESC$/i.test(p[1] ?? '') }; });
          rs = [...rs].sort((a, b) => { for (const { k, desc } of ord) { const x = key(a[k]) as any, y = key(b[k]) as any; if (x === y) continue; return (x < y ? -1 : 1) * (desc ? -1 : 1); } return 0; });
        }
        if (m[4]) rs = rs.slice(0, Number(m[4].startsWith('$') ? value(m[4], values) : m[4]));
        const cm = /^count\(\*\)(?:\s+AS\s+(\w+))?$/i.exec(m[1]!.trim());
        if (cm) return { rows: [{ [cm[1] ?? 'count']: String(rs.length) }], rowCount: 1 };
        const out = projection(m[1]!, rs).map(wire);
        return { rows: out, rowCount: out.length };
      }

      if (/^INSERT\b/i.test(sql)) {
        if (READONLY.includes(table)) throw pgError('42501', `permission denied for table ${table}`);
        m = /^INSERT INTO catalog\.\w+\s*\(([^)]*)\)\s*VALUES\s*(.+?)(?:\s+ON CONFLICT.*?)?(?:\s+RETURNING\s+(.+))?$/i.exec(sql);
        if (!m) throw new Error(`fake: unsupported SQL: ${sql.slice(0, 120)}`);
        if (/ON CONFLICT/i.test(sql)) throw new Error('fake: unsupported SQL (ON CONFLICT)');
        const cols = m[1]!.split(',').map((c) => c.trim());
        const tuples = [...m[2]!.matchAll(/\(((?:[^()']|'(?:[^']|'')*'|\([^()]*\))*)\)/g)].map((t) => splitTop(t[1]!));
        const made: Row[] = [];
        for (const t of tuples) {
          if (t.length !== cols.length) throw new Error('fake: column/value count mismatch');
          const row: Row = {};
          cols.forEach((c, i) => { row[c] = value(t[i]!, values, c); });
          if (row.tenant_id !== tenantId) throw pgError('42501', `new row violates row-level security policy for table "${table}"`);
          if (table === 'imports') { row.summary ??= {}; row.error_count ??= 0; row.warning_count ??= 0; row.version ??= 1; row.is_active ??= true; row.created_at ??= new Date(NOW); row.updated_at ??= new Date(NOW); }
          if (table === 'files' || table === 'import_issues') row.created_at ??= new Date(NOW);
          checkRow(table, row, [...visible(table), ...made]);
          made.push(row);
        }
        ins[table]!.push(...made);
        const out = m[3] ? projection(m[3], made) : [];
        return { rows: out, rowCount: made.length };
      }

      if (/^UPDATE\b/i.test(sql)) {
        if (READONLY.includes(table)) throw pgError('42501', `permission denied for table ${table}`);
        m = /^UPDATE catalog\.\w+\s+SET\s+(.+?)\s+WHERE\s+(.+?)(?:\s+RETURNING\s+(.+))?$/i.exec(sql);
        if (!m) throw new Error(`fake: unsupported SQL (UPDATE needs WHERE): ${sql.slice(0, 120)}`);
        const sets = splitTop(m[1]!).map((s) => { const p = /^(\w+)\s*=\s*(.+)$/.exec(s.trim()); if (!p) throw new Error(`fake: unsupported SET: ${s}`); return { c: p[1]!, v: p[2]!.trim() }; });
        const hit = visible(table).filter(matcher(m[2], values));
        for (const r of hit) {
          const patch: Row = { ...(patches.get(r.__ref) ?? {}) };
          for (const { c, v } of sets) {
            const inc = new RegExp(`^${c}\\s*\\+\\s*1$`, 'i').test(v);
            patch[c] = inc ? Number(r[c] ?? 0) + 1 : value(v, values, c);
            r[c] = patch[c];
          }
          const merged = { ...strip(r) };
          for (const c of REQUIRED[table] ?? []) if (merged[c] == null) throw pgError('23502', `null value in column "${c}" of relation "${table}"`);
          const bad = check(table, merged); if (bad) throw pgError('23514', `violates check constraint "${bad}"`);
          if (r.__ref.tenant_id !== tenantId) throw pgError('42501', 'rls');
          if (ins[table]!.includes(r.__ref)) Object.assign(r.__ref, patch); else patches.set(r.__ref, patch);
        }
        const out = m[3] ? projection(m[3], hit) : [];
        return { rows: out, rowCount: hit.length };
      }
      if (/^DELETE\b/i.test(sql)) throw pgError('42501', `permission denied for table ${table}`);
      throw new Error(`fake: unsupported SQL: ${sql.slice(0, 80)}`);
    }

    return {
      id, tenantId, query,
      commit() {
        if (!open) return; open = false;
        for (const t of Object.keys(ins)) for (const r of ins[t]!) {
          const pk = PK[t]!;
          if (committed[t]!.some((o) => pk.every((c) => key(o[c]) === key(r[c])))) throw pgError('23505', `duplicate key at commit (${t})`);
          committed[t]!.push(r);
        }
        for (const [ref, p] of patches) Object.assign(ref, p);
      },
      rollback() { open = false; },
    };
  }

  return { begin, seed, rows, stmts, committed };
}
