// T0B-09 — Seeds (db/seeds/001, 002, 003, 010). AC-0A-6.1 (seeds loaded by `pnpm dev:up`), done_when "prod subset defined", tests "idempotent re-run".
// Spec: 02-TRD §4.6 (seed table + idempotency rule), §3.5 (fixed tenant ids/names, actors), 05-SCHEMA §3.5/§3.7, 07-SECURITY REQ-SEC-040/044.
// Static (no DB). The live half is db/tests/seeds/T0B-09_seeds.test.sql (re-run each seed, compare row hashes, audit_log unchanged).
// Fixture: db/tests/seeds/_expected.sql is GENERATED from contracts/permissions.yaml + db/meta/system-actors.yaml by expectedSql() below;
//   this file fails when it is stale. Regenerate: `set T0B09_WRITE=1 && node --test tests/db/T0B-09.seeds.test.mjs` (tester-owned fixture).
// Prod subset (tester-defined from 02-TRD §4.6 "Production runs only 001–003"): seed files whose numeric prefix is < 010.
import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const SEEDS = join(REPO, "db/seeds");
const EXPECTED = join(REPO, "db/tests/seeds/_expected.sql");
const read = (p) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");
const { parse } = createRequire(join(REPO, "contracts/package.json"))("yaml");

const TENANT_A = "01a1a98a-ac40-7000-8000-00000000a001";
const TENANT_B = "01a1a98a-ac40-7000-8000-00000000b001";
const ROLES = ["tenant_admin", "front_desk", "finance", "lab_technologist", "pathologist", "lab_manager", "centre_staff", "phlebotomist", "owner_viewer", "radiologist"];

const perms = parse(read(join(REPO, "contracts/permissions.yaml")));
const actors = JSON.parse(read(join(REPO, "db/meta/system-actors.yaml")).replace(/^\s*#.*$/gm, "")).system_actors;
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

function expectedSql() {
  const roleCodes = perms.roles.map((r) => r.code);
  const rp = [];
  for (const p of perms.permissions) for (const r of p.roles ?? []) if (roleCodes.includes(r)) rp.push([r, p.code]);
  return [
    "-- GENERATED by tests/db/T0B-09.seeds.test.mjs from contracts/permissions.yaml + db/meta/system-actors.yaml. Do not edit. Synthetic only.",
    "CREATE TEMP TABLE exp_permissions (code text PRIMARY KEY, privileged boolean NOT NULL);",
    "CREATE TEMP TABLE exp_roles (role_code text PRIMARY KEY, mfa_required boolean NOT NULL);",
    "CREATE TEMP TABLE exp_role_perms (role_code text NOT NULL, permission_code text NOT NULL, PRIMARY KEY (role_code, permission_code));",
    "CREATE TEMP TABLE exp_system_actors (module text PRIMARY KEY, actor_id uuid NOT NULL);",
    `INSERT INTO exp_permissions VALUES\n${perms.permissions.map((p) => `  (${q(p.code)}, ${p.privileged})`).join(",\n")};`,
    `INSERT INTO exp_roles VALUES\n${perms.roles.map((r) => `  (${q(r.code)}, ${r.mfa_required})`).join(",\n")};`,
    `INSERT INTO exp_role_perms VALUES\n${rp.map(([r, c]) => `  (${q(r)}, ${q(c)})`).join(",\n")};`,
    `INSERT INTO exp_system_actors VALUES\n${Object.entries(actors).map(([m, a]) => `  (${q(m)}, ${q(a)})`).join(",\n")};`,
    "",
  ].join("\n");
}

const files = () => readdirSync(SEEDS).filter((f) => f.endsWith(".sql")).sort();
const prefix = (f) => Number(f.slice(0, 3));
const find = (n) => files().find((f) => f.startsWith(n));
const body = (n) => { const f = find(n); assert.ok(f, `db/seeds/${n}_*.sql missing`); return read(join(SEEDS, f)); };
const stripComments = (s) => s.replace(/--[^\n]*/g, "");
const inserts = (sql) => stripComments(sql).split(/;\s*(?:\n|$)/).filter((st) => /\bINSERT\s+INTO\b/i.test(st));

if (process.env.T0B09_WRITE) { mkdirSync(dirname(EXPECTED), { recursive: true }); writeFileSync(EXPECTED, expectedSql()); }

describe("T0B-09 fixture", () => {
  it("db/tests/seeds/_expected.sql is current", () => {
    assert.ok(existsSync(EXPECTED), "expected-fixture missing");
    assert.equal(read(EXPECTED), expectedSql(), "stale: regenerate with T0B09_WRITE=1");
  });
});

describe("T0B-09 files and naming (02-TRD §4.6)", () => {
  it("001, 002, 003, 010 exist with <nnn>_<schema>__<name>.sql names", () => {
    for (const [n, re] of [["001", /^001_core__g_permissions\.sql$/], ["002", /^002_core__g_system_actors\.sql$/], ["003", /^003_audit__g_cs_access_actions\.sql$/], ["010", /^010_core__synthetic_tenants\.sql$/]])
      assert.match(find(n) ?? "(missing)", re, `seed ${n}`);
    for (const f of files()) assert.match(f, /^\d{3}_[a-z0-9]+__[a-z0-9_]+\.sql$/, `bad seed name ${f}`);
  });
  it("every seed is idempotent, role-scoped (001-004 lims_owner, 010+ lims_app) and destructive-free", () => {
    for (const f of files()) {
      const sql = read(join(SEEDS, f)), code = stripComments(sql);
      if (/^00[1-4]_/.test(f)) {
        // class-G seeds keep lims_owner (LD-30)
        assert.match(code, /SET\s+LOCAL\s+ROLE\s+lims_owner/i, `${f}: must run SET LOCAL ROLE lims_owner`);
      } else if (/^(0[1-9]\d|[1-9]\d\d)_/.test(f)) {
        // tenant-scoped seeds (LD-30): lims_app after claims so real <table>__insert__tenant WITH CHECK applies
        const role = code.search(/SET\s+LOCAL\s+ROLE\s+lims_app/i);
        const claims = code.search(/set_config\s*\(\s*'request\.jwt\.claims'[^;]*?,\s*true\s*\)/i);
        assert.ok(role >= 0, `${f}: must run SET LOCAL ROLE lims_app (LD-30)`);
        assert.ok(claims >= 0 && claims < role, `${f}: SET LOCAL ROLE lims_app must come after set_config('request.jwt.claims', ..., true)`);
        assert.doesNotMatch(code, /SET\s+LOCAL\s+ROLE\s+lims_owner/i, `${f}: tenant-scoped seed must not use lims_owner (LD-30)`);
      }
      for (const st of inserts(sql)) assert.match(st, /ON\s+CONFLICT[\s\S]*DO\s+NOTHING/i, `${f}: INSERT without ON CONFLICT ... DO NOTHING:\n${st.slice(0, 160)}`);
      assert.doesNotMatch(code, /\b(DELETE\s+FROM|TRUNCATE|DROP\s+(TABLE|SCHEMA|POLICY)|DISABLE\s+ROW\s+LEVEL|NO\s+FORCE\s+ROW|session_replication_role|ALTER\s+ROLE|CREATE\s+ROLE)\b/i, `${f}: destructive/RLS-bypass statement`);
      assert.doesNotMatch(code, /ON\s+CONFLICT[^;]*DO\s+UPDATE/i, `${f}: DO UPDATE would rewrite rows on re-run`);
      assert.doesNotMatch(code, /\bBEGIN\s*;|\bCOMMIT\s*;/i, `${f}: runner wraps seeds in a transaction (--single-transaction)`);
      assert.doesNotMatch(code, /\b(now|random|gen_random_uuid|uuidv7|clock_timestamp)\s*\(/i, `${f}: non-deterministic value breaks idempotent re-run`);
    }
  });
});

describe("T0B-09 001 permissions", () => {
  it("inserts core.g_permissions with every code of permissions.yaml (one tuple each, no extras)", () => {
    const sql = body("001");
    assert.match(stripComments(sql), /INSERT\s+INTO\s+core\.g_permissions/i);
    // row shape: one VALUES tuple per permission starting with the quoted code (flags are checked live in the pgTAP suite)
    const codes = [...sql.matchAll(/\(\s*'([a-z_]+\.[a-z_]+\.[a-z_]+)'/g)].map((m) => m[1]);
    assert.deepEqual([...new Set(codes)].sort(), perms.permissions.map((p) => p.code).sort(), "001 must contain exactly the yaml codes (no extras, no dupes elsewhere)");
    assert.equal(codes.length, new Set(codes).size, "duplicate code row in 001");
  });
});

describe("T0B-09 002 system actors", () => {
  it("inserts core.g_system_actors with exactly the fixed UUIDs of db/meta/system-actors.yaml", () => {
    const sql = body("002");
    assert.match(stripComments(sql), /INSERT\s+INTO\s+core\.g_system_actors/i);
    for (const [m, id] of Object.entries(actors)) assert.match(sql, new RegExp(`'${m}'\\s*,\\s*'${id}'`), `${m} -> ${id} missing`);
    const ids = [...sql.matchAll(/'([0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[0-9a-f]{4}-[0-9a-f]{12})'/g)].map((m) => m[1]);
    assert.deepEqual([...new Set(ids)].sort(), Object.values(actors).sort(), "no extra / changed actor ids");
  });
});

describe("T0B-09 010 synthetic tenants (02-TRD §3.5, §4.6)", () => {
  const sql = () => body("010");
  it("fixed tenant ids and names, tenant_a / tenant_b", () => {
    const s = sql();
    for (const [id, code, name] of [[TENANT_A, "tenant_a", "Synthetic Lab Alpha"], [TENANT_B, "tenant_b", "Synthetic Lab Beta"]]) {
      assert.ok(s.includes(id), `${id} missing`); assert.ok(s.includes(`'${code}'`), `${code} missing`); assert.ok(s.includes(name), `${name} missing`);
    }
  });
  it("populates tenants, branches, centres (incl. home_collection), roles, role_permissions, users, memberships, membership_roles", () => {
    const code = stripComments(sql());
    for (const t of ["tenants", "branches", "collection_centres", "roles", "role_permissions", "users", "memberships", "membership_roles", "membership_centres"])
      assert.match(code, new RegExp(`INSERT\\s+INTO\\s+core\\.${t}\\b`, "i"), `no INSERT INTO core.${t}`);
    assert.match(code, /'home_collection'/);
    for (const r of ROLES) assert.match(code, new RegExp(`'${r}'`), `default role ${r} missing`);
  });
  it("sets claims per tenant via set_config(..., true) so RLS WITH CHECK applies; never writes memberships.is_active", () => {
    const code = stripComments(sql());
    assert.match(code, /set_config\(\s*'request\.jwt\.claims'\s*,[\s\S]*?,\s*true\s*\)/i);
    assert.ok((code.match(/set_config\(\s*'request\.jwt\.claims'/gi) ?? []).length >= 2, "claims must be set for each tenant");
    for (const st of inserts(sql())) if (/INSERT\s+INTO\s+core\.memberships\b/i.test(st)) {
      const cols = /\(([^)]*)\)\s*(?:VALUES|SELECT|OVERRIDING)/is.exec(st.replace(/INSERT\s+INTO\s+core\.memberships/i, ""))?.[1] ?? "";
      assert.doesNotMatch(cols, /\bis_active\b/i, "core.memberships.is_active is GENERATED (08 A3.4)");
    }
  });
  it("is synthetic only: no real-looking contact data or secrets", () => {
    const s = sql();
    assert.doesNotMatch(s, /@(?!example\.(com|org|net)|lims\.test|synthetic\.test|invalid)[a-z0-9-]+\.[a-z]{2,}/i, "email domain must be reserved/synthetic");
    assert.doesNotMatch(s, /\+977\s?9[78]\d{8}|\b9[78]\d{8}\b/, "Nepali mobile-shaped number");
    assert.doesNotMatch(s, /(password|secret|api[_-]?key|token|BEGIN [A-Z ]*PRIVATE KEY)\s*['"=:]/i, "no secrets in seeds");
    assert.doesNotMatch(s, /eyJ[A-Za-z0-9_-]{10,}\./, "JWT-shaped string");
  });
});

describe("T0B-09 prod subset (production runs only 001-004; LD-59)", () => {
  const prod = () => files().filter((f) => prefix(f) < 10);
  it("prod subset = exactly 001, 002, 003, 004 (004 = reporting message templates, LD-59)", () => assert.deepEqual(prod().map((f) => f.slice(0, 3)), ["001", "002", "003", "004"]));
  it("prod seeds touch only class-G coded sets: no tenants, users, memberships, centres or synthetic ids", () => {
    for (const f of prod()) {
      const s = read(join(SEEDS, f)), code = stripComments(s);
      assert.doesNotMatch(code, /\bcore\.(tenants|branches|collection_centres|users|memberships|membership_\w+|roles|role_permissions)\b/i, `${f} writes tenant-scoped data`);
      assert.ok(!s.includes(TENANT_A) && !s.includes(TENANT_B) && !/tenant_[ab]\b|Synthetic Lab/.test(s), `${f} references synthetic tenants`);
      assert.doesNotMatch(code, /set_config\(\s*'request\.jwt\.claims'/i, `${f}: class-G seed needs no claims`);
    }
  });
  it("only 010+ may be synthetic; 010 is outside the prod subset and orders after 001-003", () => {
    assert.ok(find("010"), "010 missing"); assert.ok(prefix(find("010")) >= 10);
    for (const f of files()) if (/synthetic/.test(f)) assert.ok(prefix(f) >= 10, `${f} synthetic seed must not be in the prod range`);
  });
});

