// ---------------------------------------------------------------- JSON Schema / OpenAPI schema → TS type text
type Docs = Map<string, any>;
function deref(docs: Docs, ref: string, ctx: string): { node: unknown; ctx: string } {
  const [base, ptr = ""] = ref.split("#");
  const id = base || ctx;
  let node = docs.get(id);
  if (node === undefined) throw new Error(`unresolved $ref ${ref} (from ${ctx})`);
  for (const seg of ptr.split("/").filter(Boolean)) {
    node = node?.[seg.replace(/~1/g, "/").replace(/~0/g, "~")];
    if (node === undefined) throw new Error(`unresolved $ref ${ref} (from ${ctx})`);
  }
  return { node, ctx: id };
}
const wrap = (t: string) => (/[|&]/.test(t) ? `(${t})` : t);

function toTs(docs: Docs, s: unknown, ctx: string, ind = "", seen: string[] = []): string {
  if (!isObj(s)) return "unknown";
  if (typeof s.$ref === "string") {
    const key = `${ctx}|${s.$ref}`;
    if (seen.includes(key)) return "unknown"; // recursive schema
    const r = deref(docs, s.$ref, ctx);
    return toTs(docs, r.node, r.ctx, ind, [...seen, key]);
  }
  if ("const" in s) return q(s.const);
  if (Array.isArray(s.enum)) return s.enum.map(q).join(" | ") || "never";
  const parts: string[] = [];
  for (const k of ["allOf"]) if (Array.isArray(s[k])) for (const x of s[k]) parts.push(wrap(toTs(docs, x, ctx, ind, seen)));
  for (const k of ["anyOf", "oneOf"])
    if (Array.isArray(s[k])) parts.push(`(${s[k].map((x: unknown) => toTs(docs, x, ctx, ind, seen)).join(" | ")})`);
  const types: string[] = Array.isArray(s.type) ? s.type : s.type ? [s.type] : s.properties ? ["object"] : [];
  const base = types.map((t) => {
    if (t === "string") return "string";
    if (t === "integer" || t === "number") return "number";
    if (t === "boolean") return "boolean";
    if (t === "null") return "null";
    if (t === "array") return `${wrap(s.items ? toTs(docs, s.items, ctx, ind, seen) : "unknown")}[]`;
    return objTs(docs, s, ctx, ind, seen);
  });
  if (base.length) parts.push(base.length > 1 ? `(${base.join(" | ")})` : base[0]!);
  if (!parts.length) return "unknown";
  return parts.join(" & ");
}

function objTs(docs: Docs, s: Record<string, any>, ctx: string, ind: string, seen: string[]): string {
  const props = isObj(s.properties) ? Object.keys(s.properties) : [];
  const ap = s.additionalProperties;
  if (!props.length) return ap === false ? "Record<string, never>" : `Record<string, ${isObj(ap) ? toTs(docs, ap, ctx, ind, seen) : "unknown"}>`;
  const req = new Set<string>(Array.isArray(s.required) ? s.required : []);
  const lines = props.map((p) => `${ind}  ${ident(p)}${req.has(p) ? "" : "?"}: ${toTs(docs, s.properties[p], ctx, ind + "  ", seen)};`);
  if (ap !== undefined && ap !== false) lines.push(`${ind}  [key: string]: unknown;`);
  return `{\n${lines.join("\n")}\n${ind}}`;
}

