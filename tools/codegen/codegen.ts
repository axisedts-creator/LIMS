function genEvents(evDocs: Docs, events: { type: string; schema: any }[], ic: string) {
  const s = ic.indexOf("### 3.25 Event summary matrix");
  if (s < 0) throw new Error("03-IC §3.25 not found");
  const section = ic.slice(s, ic.indexOf("\n### ", s + 5));
  const matrix = new Map<string, { producerChunk: string; consumers: string[] }>();
  for (const m of section.matchAll(/^\|\s*\d+\s*\|\s*([a-z_.]+\.v\d+)[^|]*\|\s*(C\d+)\s*\|([^|]*)\|/gm))
    matrix.set(m[1]!, { producerChunk: m[2]!, consumers: (m[3]!.replace(/\([^)]*\)/g, "").match(/C\d+/g) ?? []).flatMap(chunkModules) });
  const types = events.map((e) => e.type).sort(cmp);
  const producers: Record<string, string[]> = {};
  const consumers: Record<string, string[]> = {};
  const payloads: string[] = [];
  for (const e of [...events].sort((a, b) => cmp(a.type, b.type))) {
    const parts = [e.schema, ...(e.schema.allOf ?? [])];
    const producer = parts.map((p: any) => p?.properties?.producer?.const).find(Boolean) ?? e.type.split(".")[0];
    const row = matrix.get(e.type);
    if (row && MODULE_OWNERS[producer] !== row.producerChunk) throw new Error(`${e.type}: producer ${producer} ≠ 03-IC §3.25 ${row.producerChunk}`);
    (producers[producer] ??= []).push(e.type);
    for (const c of row?.consumers ?? []) (consumers[c] ??= []).push(e.type);
    const payload = parts.map((p: any) => p?.properties?.payload).find(Boolean);
    payloads.push(`  ${q(e.type)}: ${payload ? toTs(evDocs, payload, e.schema.$id, "  ") : "unknown"};`);
  }
  const rec = (r: Record<string, string[]>) => Object.keys(r).sort(cmp).map((k) => `  ${k}: [${sorted(r[k]!).map(q).join(", ")}],`).join("\n");
  return `${TS_H}
export type EventType =
${types.map((t) => `  | ${q(t)}`).join("\n")};

export interface EventPayloads {
${payloads.join("\n")}
}

export type EventPayload<E extends EventType> = EventPayloads[E];

// Producer module → event types (schema \`producer\` const, cross-checked with 03-IC §3.25).
export const EVENT_PRODUCERS: Readonly<Record<string, readonly EventType[]>> = {
${rec(producers)}
};

// Consumer module → event types (03-IC §3.25; C4 → frontdesk + billing [CONV]; non-module consumers such as C1 metrics omitted).
export const EVENT_CONSUMERS: Readonly<Record<string, readonly EventType[]>> = {
${rec(consumers)}
};
`;
}

function genPortConsumers(ic: string) {
  const out: Record<string, string[]> = {};
  for (const m of ic.matchAll(/^### 4\.\d+ `(\w+Port)` — (.*)$/gm)) {
    const port = m[1]!;
    const owner = PORT_MODULES[port];
    if (!owner) throw new Error(`03-IC port ${port} has no owner module in PORT_MODULES`);
    // keep "(`module` only)" qualifiers, drop every other parenthetical, then cut at the first " — ".
    const text = m[2]!.replace(/\((`\w+`) only\)/g, "<$1>").replace(/\([^()]*\)/g, "");
    const seg = /consumers?:?\s+(.*?)(?:\s+—|$)/.exec(text)?.[1] ?? "";
    const mods = /^all\b/.test(seg.trim())
      ? MODULES.filter((x) => x !== owner)
      : [...seg.matchAll(/C\d+(?:\s*<`(\w+)`>)?/g)].flatMap((c) => (c[1] ? [c[1]] : chunkModules(c[0].trim())));
    for (const x of mods) if (!MODULES.includes(x)) throw new Error(`03-IC ${port}: unknown consumer module ${x}`);
    out[port] = sorted(mods);
  }
  const ports = Object.keys(out).sort(cmp);
  if (q(ports) !== q(Object.keys(PORT_MODULES).sort(cmp))) throw new Error(`03-IC §4 ports ${ports} ≠ PORT_MODULES`);
  return `${TS_H}
export type ModuleName =
${MODULES.map((x) => `  | ${q(x)}`).join("\n")};

export type PortName =
${ports.map((p) => `  | ${q(p)}`).join("\n")};

// 03-IC §4.x heading consumer lists (08 A19 P-46); "all" = every module except the owner.
export const PORT_CONSUMERS: Readonly<Record<PortName, readonly ModuleName[]>> = {
${ports.map((p) => `  ${p}: [${out[p]!.map(q).join(", ")}],`).join("\n")}
};
`;
}

// openapi-typescript keys: numeric statuses unquoted (openapi-fetch matches them as numbers).
const status = (s: string) => (/^\d+$/.test(s) || s === "default" ? s : q(s));

function paramBlock(ps: { name: string; required: boolean; type: Ty }[], ind: string) {
  return `{\n${ps.map((p) => `${ind}  ${ident(p.name)}${p.required ? "" : "?"}: ${p.type(ind + "  ")};`).join("\n")}\n${ind}}`;
}

function genTsDomain(ops: Op[]) {
  const byPath = new Map<string, Op[]>();
  for (const o of ops) byPath.set(o.path, [...(byPath.get(o.path) ?? []), o]);
  const paths = [...byPath].map(([p, os]) => `  ${q(p)}: {\n${os.map((o) => `    ${o.method}: operations[${q(o.id)}];`).join("\n")}\n  };`).join("\n");
  const opText = [...ops].sort((a, b) => cmp(a.id, b.id)).map((o) => {
    const prm = (["query", "header", "path"] as const).map((k) => {
      const ps = o.params[k];
      if (!ps.length) return `      ${k}?: never;`;
      return `      ${k}${ps.some((p) => p.required) ? "" : "?"}: ${paramBlock(ps, "      ")};`;
    });
    const body = o.body ? `    requestBody${o.body.required ? "" : "?"}: {\n      content: {\n        ${q(o.body.media)}: ${o.body.type("        ")};\n      };\n    };` : "    requestBody?: never;";
    const resp = o.responses.map((r) => `      ${status(r.status)}: {\n        headers: { [name: string]: unknown };\n${r.content.length
      ? `        content: {\n${r.content.map((c) => `          ${q(c.media)}: ${c.type("          ")};`).join("\n")}\n        };`
      : "        content?: never;"}\n      };`).join("\n");
    return `  ${o.id}: {\n    parameters: {\n${prm.join("\n")}\n      cookie?: never;\n    };\n${body}\n    responses: {\n${resp}\n    };\n  };`;
  }).join("\n");
  return `${TS_H}
// openapi-typescript-shaped types (paths / operations) for openapi-fetch.
export interface paths {
${paths}
}

export interface operations {
${opText}
}
`;
}

