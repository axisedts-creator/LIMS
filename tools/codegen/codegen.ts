// gen-msw (02-TRD §5.3/§5.5, AC-0C-4.2): one handler per operationId, any origin, lowest 2xx + first JSON example.
// ponytail: `:` inside a literal path segment would read as an MSW param; no spec path has one yet.
function genMsw(oas: Docs, domains: string[]) {
  const res = (x: any, ctx: string): { node: any; ctx: string } =>
    isObj(x) && typeof x.$ref === "string" ? (({ node, ctx: c }) => res(node, c))(deref(oas, x.$ref, ctx)) : { node: x, ctx };
  const lines: { key: string; id: string; text: string }[] = [];
  for (const d of domains) {
    const spec = oas.get(`${d}.yaml`);
    for (const path of Object.keys(spec.paths ?? {}).sort(cmp)) for (const method of METHODS) {
      const op = spec.paths[path][method];
      if (!isObj(op) || method === "trace") continue; // MSW has no trace helper
      // T0C-10.C15 (LD-103): redirect-only browser callbacks (payments P31–P33) have no 2xx; mock their lowest 3xx without a body.
      const codes = Object.keys(op.responses ?? {});
      const ok = codes.filter((s) => /^2\d\d$/.test(s)).sort(cmp)[0] ?? codes.filter((s) => /^3\d\d$/.test(s)).sort(cmp)[0];
      if (!ok) throw new Error(`${op.operationId}: no 2xx/3xx response for gen-msw`);
      const r = res(op.responses[ok], `${d}.yaml`);
      const json = r.node?.content?.["application/json"];
      const first = isObj(json?.examples) ? Object.values(json.examples)[0] : undefined;
      const ex = first !== undefined ? res(first, r.ctx).node?.value : json?.example;
      const url = "*" + path.replace(/\{(\w+)\}/g, ":$1");
      const body = ex === undefined ? `new HttpResponse(null, { status: ${ok} })` : `HttpResponse.json(${JSON.stringify(ex)}, { status: ${ok} })`;
      // MSW takes the first match: key maps `:param` to U+FFFF so literal siblings (possible-duplicates) sort before templated ones.
      lines.push({ key: url.replace(/:\w+/g, "￿"), id: op.operationId, text: `  // ${op.operationId}\n  http.${method}(${q(url)}, () => ${body}),` });
    }
  }
  return `${TS_H}
import { http, HttpResponse } from "msw";

export const handlers = [
${lines.sort((a, b) => cmp(a.key, b.key) || cmp(a.id, b.id)).map((l) => l.text).join("\n")}
];
`;
}

// ---------------------------------------------------------------- entry points
export function generateAll(rootDir: string): Record<string, string> {
  const inp = loadInputs(rootDir);
  const out: Record<string, string> = {};
  const err = genErrorCodes(inp.errors);
  out["contracts/ports/generated/error-codes.ts"] = err.ts;
  out["packages/shared-dart/lib/src/error_codes.g.dart"] = err.dart;
  const perm = genPermissions(inp.permissions, TS_H, SQL_H);
  out["contracts/ports/generated/permissions.ts"] = perm.ts;
  out["db/seeds/001_core__g_permissions.sql"] = perm.sql;
  const acc = genAccessActions(inp.ic, TS_H, SQL_H);
  out["contracts/ports/generated/access-actions.ts"] = acc.ts;
  out["db/seeds/003_audit__g_cs_access_actions.sql"] = acc.sql;
  out["contracts/ports/generated/port-consumers.ts"] = genPortConsumers(inp.ic);
  out["contracts/ports/generated/events.ts"] = genEvents(inp.evDocs, inp.events, inp.ic);
  const routes = genRoutes(inp.routes);
  out["packages/shared-ts/src/routes/generated.ts"] = routes.ts;
  out["packages/shared-dart/lib/src/routes.g.dart"] = routes.dart;
  const all: Op[] = [];
  for (const d of inp.domains) {
    const ops = operations(inp.oas, `${d}.yaml`);
    all.push(...ops);
    out[`packages/api-client-ts/src/${d}.ts`] = genTsDomain(ops);
    out[`packages/api-client-dart/lib/${d}.dart`] = genDartDomain(d, ops);
  }
  const ids = all.map((o) => o.id);
  if (new Set(ids).size !== ids.length) throw new Error("duplicate operationId across specs");
  out["packages/api-client-ts/src/client.ts"] = genTsClient(inp.domains);
  out["packages/api-client-ts/src/server/operations.ts"] = genOperations(all);
  out["packages/api-client-dart/lib/src/transport.dart"] = DART_TRANSPORT;
  out["packages/fakes/src/msw/handlers.generated.ts"] = genMsw(inp.oas, inp.domains);
  return Object.fromEntries(Object.keys(out).sort(cmp).map((k) => [k, out[k]!]));
}

export function staleFiles(rootDir: string): string[] {
  return Object.entries(generateAll(rootDir)).filter(([p, text]) => {
    const f = join(rootDir, p);
    return !existsSync(f) || readFileSync(f, "utf8").replace(/\r\n/g, "\n") !== text;
  }).map(([p]) => p);
}

export function writeAll(rootDir: string): void {
  for (const [p, text] of Object.entries(generateAll(rootDir))) {
    const f = join(rootDir, p);
    mkdirSync(dirname(f), { recursive: true });
    writeFileSync(f, text);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(HERE, "../..");
  const rules = checkPermissionRules(parse(readFileSync(join(root, "contracts/permissions.yaml"), "utf8")));
  for (const x of rules) console.error(`gen-permissions: [${x.rule}] ${x.code}: ${x.message}`);
  let failed = rules.length > 0;
  if (process.argv.includes("--check")) {
    const stale = staleFiles(root);
    for (const p of stale) console.error(`codegen-fresh: stale or missing ${p} — run pnpm codegen`);
    failed ||= stale.length > 0;
  } else writeAll(root);
  process.exit(failed ? 1 : 0);
}
