function genOperations(ops: Op[]) {
  const text = [...ops].sort((a, b) => cmp(a.id, b.id)).map((o) => {
    const blk = (k: "path" | "query" | "header") => (o.params[k].length ? paramBlock(o.params[k], "    ") : "Record<string, never>");
    const body = o.body ? (o.body.required ? o.body.type("    ") : `${wrap(o.body.type("    "))} | undefined`) : "never";
    const resp = o.responses.map((r) => `      ${status(r.status)}: ${r.content.length ? r.content.map((c) => wrap(c.type("      "))).join(" | ") : "undefined"};`).join("\n");
    return `  ${o.id}: {\n    params: ${blk("path")};\n    query: ${blk("query")};\n    headers: ${blk("header")};\n    body: ${body};\n    responses: {\n${resp}\n    };\n  };`;
  }).join("\n");
  return `${TS_H}
// Operations map operationId → { params, query, headers, body, responses } used by core Handler<'opId'> (02-TRD §5.3).
export interface Operations {
${text}
}

export type OperationId = keyof Operations;
`;
}

// ponytail: hand-rolled dependency-free Dart client; swap for openapi-generator 7.27.0 dart-dio (02-TRD §5.3) once a JDK step exists in CI.
function genDartDomain(domain: string, ops: Op[]) {
  const methods = [...ops].sort((a, b) => cmp(a.id, b.id)).map((o) => {
    const args = [
      ...o.params.path.map((p) => `required String ${camel(p.name)}`),
      ...(o.params.query.length ? ["Map<String, Object?>? query"] : []),
      ...(o.params.header.length ? ["Map<String, String>? headers"] : []),
      ...(o.body ? ["Object? body"] : []),
    ];
    let path = "";
    let last = 0;
    for (const m of o.path.matchAll(/\{(\w+)\}/g)) {
      path += dartStr(o.path.slice(last, m.index)).slice(1, -1) + `\${Uri.encodeComponent(${camel(m[1]!)})}`;
      last = m.index + m[0].length;
    }
    path += dartStr(o.path.slice(last)).slice(1, -1);
    const named = [...(o.params.query.length ? ["query: query"] : []), ...(o.params.header.length ? ["headers: headers"] : []), ...(o.body ? ["body: body"] : [])];
    return `  /// ${o.method.toUpperCase()} ${o.path}\n  Future<Object?> ${o.id}(${args.length ? `{${args.join(", ")}}` : ""}) =>\n      _send(${dartStr(o.method.toUpperCase())}, '${path}'${named.map((n) => `, ${n}`).join("")});`;
  }).join("\n\n");
  return `${TS_H}
library;

import 'src/transport.dart';

export 'src/transport.dart';

/// Operations of contracts/openapi/${domain}.yaml.
class ${pascal(domain)}Api {
  const ${pascal(domain)}Api(this._send);

  final LimsTransport _send;

${methods}
}
`;
}

