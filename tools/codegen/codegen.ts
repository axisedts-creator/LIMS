type Op = {
  id: string; method: string; path: string;
  params: Record<"path" | "query" | "header", { name: string; required: boolean; type: Ty }[]>;
  body?: { type: Ty; required: boolean; media: string };
  responses: { status: string; content: { media: string; type: Ty }[] }[];
};
type Ty = (ind: string) => string; // renders the schema's TS type at a given indent

function loadInputs(root: string) {
  const read = (p: string) => readFileSync(join(root, p), "utf8").replace(/\r\n/g, "\n");
  const openapiDir = join(root, "contracts/openapi");
  const specFiles = readdirSync(openapiDir).filter((f) => f.endsWith(".yaml")).sort(cmp);
  const oas: Docs = new Map(specFiles.map((f) => [f, parse(read(`contracts/openapi/${f}`))]));
  const eventDir = join(root, "contracts/events");
  const eventFiles = readdirSync(eventDir).filter((f) => f.endsWith(".schema.json")).sort(cmp);
  const evDocs: Docs = new Map();
  const events: { type: string; schema: any }[] = [];
  for (const f of eventFiles) {
    const d = JSON.parse(read(`contracts/events/${f}`));
    evDocs.set(d.$id, d);
    if (!f.startsWith("_")) events.push({ type: f.replace(/\.schema\.json$/, ""), schema: d });
  }
  return {
    errors: parse(read("contracts/errors.yaml")) as { code: string; http: number; owner: string; title?: string }[],
    permissions: parse(read("contracts/permissions.yaml")),
    routes: parse(read("contracts/routes.yaml")),
    ic: read("spec/program/03-INTERFACE-CATALOG.md"),
    oas, domains: specFiles.filter((f) => !f.startsWith("_")).map((f) => f.replace(/\.yaml$/, "")),
    evDocs, events,
  };
}

function operations(oas: Docs, file: string): Op[] {
  const spec = oas.get(file);
  const ops: Op[] = [];
  const res = (x: any, ctx: string): { node: any; ctx: string } => {
    if (!isObj(x) || typeof x.$ref !== "string") return { node: x, ctx };
    const r = deref(oas, x.$ref, ctx);
    return res(r.node, r.ctx);
  };
  for (const path of Object.keys(spec.paths ?? {}).sort(cmp)) {
    const item = spec.paths[path];
    for (const method of METHODS) {
      const op = item[method];
      if (!isObj(op)) continue;
      const params: Op["params"] = { path: [], query: [], header: [] };
      for (const raw of [...(item.parameters ?? []), ...(op.parameters ?? [])]) {
        const { node: p, ctx } = res(raw, file);
        if (p.in in params) params[p.in as "path"].push({ name: p.name, required: p.in === "path" || !!p.required, type: (i) => toTs(oas, p.schema, ctx, i) });
      }
      let body: Op["body"];
      if (op.requestBody) {
        const { node: rb, ctx } = res(op.requestBody, file);
        const media = Object.keys(rb.content ?? {}).sort(cmp)[0];
        if (media) body = { media, required: !!rb.required, type: (i) => toTs(oas, rb.content[media].schema, ctx, i) };
      }
      const responses = Object.keys(op.responses ?? {}).sort(cmp).map((status) => {
        const { node: r, ctx } = res(op.responses[status], file);
        return { status, content: Object.keys(r.content ?? {}).sort(cmp).map((media) => ({ media, type: (i: string) => toTs(oas, r.content[media].schema, ctx, i) })) };
      });
      // operationId and param names become TS keys / Dart identifiers: refuse anything that is not a plain identifier.
      if (!/^[a-z][A-Za-z0-9]*$/.test(op.operationId ?? "")) throw new Error(`${file} ${method} ${path}: bad operationId ${q(op.operationId)}`);
      for (const p of params.path) if (!/^[a-z_][a-z0-9_]*$/.test(p.name)) throw new Error(`${op.operationId}: bad path param ${q(p.name)}`);
      ops.push({ id: op.operationId, method, path, params, ...(body ? { body } : {}), responses });
    }
  }
  return ops;
}

