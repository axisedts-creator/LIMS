// LD-240 / SEC-HYG-1 (security audit 2026-11-15 check 11.3): generates docs/stubbed-operations.md, the operationIds that still map to a fail-closed stub, per module.
//   node tools/lint/gen-stubbed-operations.mjs                  write docs/stubbed-operations.md
//   node tools/lint/gen-stubbed-operations.mjs --out <file>     write the generated text to <file> instead
//   node tools/lint/gen-stubbed-operations.mjs --check [<file>] exit 1 when <file> (default the doc) is missing or differs from the generated text
// Method (static, no TypeScript runtime): a module has stubs only when its handler index (modules/<m>/handlers/index.ts, else modules/<m>/index.ts) defines a
// "not implemented" fallback. Its operationIds are those of contracts/openapi/<m>.yaml. An id is real when it is a key (`id,` `id:` `id }`) in that index or in a
// file the index spreads (`...xHandlers`); `id: stub` stays a stub. ponytail: token match, not a parse; a spread file that lists an id it does not register
// would hide a stub. Upgrade: load the manifests through a TS runner and probe handlers.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const MODULES = join(ROOT, 'services', 'api', 'src', 'modules');
const OPENAPI = join(ROOT, 'contracts', 'openapi');
const DOC = join(ROOT, 'docs', 'stubbed-operations.md');

const code = (file) => readFileSync(file, 'utf8').replace(/\r\n/g, '\n').replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
const noImports = (s) => s.replace(/^import[\s\S]*?;$/gm, '');

function tsFile(base) {
  for (const f of [base.replace(/\.js$/, '.ts'), `${base}.ts`, join(base, 'index.ts')]) if (existsSync(f) && f.endsWith('.ts')) return f;
  return undefined;
}

function stubsOf(module) {
  const index = [join(MODULES, module, 'handlers', 'index.ts'), join(MODULES, module, 'index.ts')].find(existsSync);
  const yaml = join(OPENAPI, `${module}.yaml`);
  if (!index || !existsSync(yaml)) return [];
  const src = code(index);
  if (!/not implemented/.test(src)) return [];
  // import map: local name -> file, for the `...name` spreads of the index
  const files = new Map();
  for (const m of src.matchAll(/import\s*\{([^}]*)\}\s*from\s*'(\.[^']*)'/g)) {
    for (const part of m[1].split(',')) {
      const local = part.trim().split(/\s+as\s+/).pop();
      if (local) files.set(local, m[2]);
    }
  }
  for (const m of src.matchAll(/import\s*\*\s*as\s+(\w+)\s+from\s*'(\.[^']*)'/g)) files.set(m[1], m[2]); // namespace import: the file's `export const <operationId>` are the keys
  let text = noImports(src);
  for (const m of src.matchAll(/\.\.\.\s*(\w+)/g)) {
    const spec = files.get(m[1]);
    const f = spec && tsFile(resolve(dirname(index), spec));
    if (f) text += `\n${noImports(code(f))}`;
  }
  const ids = [...new Set([...readFileSync(yaml, 'utf8').matchAll(/^\s*operationId:\s*(\S+)\s*$/gm)].map((x) => x[1]))];
  const real = (id) => new RegExp(`(^|[\\s{,])${id}\\s*(,|:(?!\\s*(stub|notImplemented)\\b)|\\})|export\\s+(async\\s+)?(const|function)\\s+${id}\\b`, 'm').test(text);
  return ids.filter((id) => !real(id)).sort();
}

export function generate() {
  const out = [
    '# Stubbed operations',
    '',
    'Generated by `tools/lint/gen-stubbed-operations.mjs` (LD-240, security audit 2026-11-15 check 11.3). Do not edit by hand: run the script and commit the result.',
    'An operationId listed here is in its module\'s operation list but has no real handler yet, so it answers the fail-closed stub (`common.internal`; 501 on dev).',
    'A test fails when this file is stale.',
    '',
  ];
  for (const m of readdirSync(MODULES, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()) {
    const ids = stubsOf(m);
    if (ids.length) out.push(`## ${m}`, '', ...ids.map((id) => `- \`${id}\``), '');
  }
  return `${out.join('\n').trimEnd()}\n`;
}

const args = process.argv.slice(2);
if (args[0] === '--check') {
  const file = args[1] ?? DOC;
  const ok = existsSync(file) && readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === generate();
  if (!ok) console.error(`${file} is stale or missing: run node tools/lint/gen-stubbed-operations.mjs and commit docs/stubbed-operations.md`);
  process.exit(ok ? 0 : 1);
} else {
  writeFileSync(args[0] === '--out' ? args[1] : DOC, generate());
}
